-- runs both.
--
--   clubs          a name (unique, any case) and a crest; anyone signed in can
--                  list them by name
--   club_members   who's in which club, one club at a time; members see each
--                  other's names and nothing else about each other
--   club_invites   an invite by username from any member; it lands in the
--                  invitee's notifications; the size cap is checked on accept
--   club_targets   the club's weekly target in minutes (any member may set it);
--                  without one, defaultMinPerMember × members
--   club_relays    the route the club is carrying round the island
--
-- Totals only: club_board() returns the club's minutes this week and its relay
-- kilometres, summed over verified work (earns(), the XP rule), never anyone's
-- days. Leaving is free and says nothing to anyone. The club room is
-- room_messages with a club_id: the same rate limit, removal, reports and
-- blocking as General, readable and writable by members only.

