-- 0027: reward chests (docs/REWARDS.md). Mirrors js/core/rewards.js;
-- tests/rewards-sql.test.js runs both over the same cases.
--
--   - Every session that earns XP from chest_rules().since on, lasting at least
--     minMinutes, leaves a chest, at most perDay a day. my_chests() makes the ones
--     that are due (so a Strava sync, the webhook or the app logging a session all
--     lead to one the next time the app asks) and lists them.
--   - The tier is rolled once, here, with random(), against the session's
--     difficulty bracket (chest_difficulty(), from what was measured). A switched-off
--     tier (epic, until its animation exists) rolls as the tier below it.
--   - Opening (open_chest()) pays the chest's bonus: an earning in wallet_fold()
--     (rank 6) from the moment it was opened, so balances stay derived and an
--     unopened chest is worth nothing yet. A chest is made once per session and
--     once per Strava activity, so deleting and re-importing doesn't roll again.
--   - Admins (app_admins, 0012) can gift themselves a chest of any switched-on
--     tier, to try the animations (admin_gift_chest()).
--   - Written without DROP or REVOKE: who may do what is checked inside each
--     function, so the migration applies without a destructive-statement prompt.

