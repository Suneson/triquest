-- isRestDay() in js/core/rest.js: a day with no planned (non-optional,
-- not-from-Strava) session, in a run of at most two such days with planned
-- days on both sides.
create or replace function public.is_rest_day(p_user uuid, p_date date)
returns boolean language sql stable set search_path = public as $$
  with p as (
    select distinct w.date from public.workouts w
    where w.user_id = p_user and w.source is distinct from 'strava'
      and not coalesce((w.extra ->> 'optional')::boolean, false)
  ),
  b as (select (select max(date) from p where date < p_date) as prev,
               (select min(date) from p where date > p_date) as next)
  select not exists (select 1 from p where date = p_date)
     and b.prev is not null and b.next is not null
     and b.next - b.prev - 1 <= 2
  from b;
$$;

-- The stamp trigger (0017) also stamps on_rest_day, once, when a session
-- first earns. Clients can't write it.
create or replace function public.workouts_stamp_boost()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  gel public.user_boosts;
  cap int;
begin
  if tg_op = 'UPDATE' then
    new.boost := old.boost;
    new.first_earned_at := old.first_earned_at;
    new.on_rest_day := old.on_rest_day;
  else
    new.boost := null;
    new.first_earned_at := null;
    new.on_rest_day := null;
  end if;
  if new.first_earned_at is null and public.earns(new) then
    new.first_earned_at := now();
    new.on_rest_day := public.is_rest_day(new.user_id, new.date);
    new.boost := public.boost_stamp(new, now());
    select b.* into gel
    from public.user_boosts b
    where b.user_id = new.user_id and b.until_next and b.workout_id is null and b.started_at <= now()
      and coalesce((select e from public.session_span(new)), now())
          >= b.started_at - make_interval(hours => (public.gear_rules() -> 'fuel' ->> 'graceHours')::int)
    order by b.started_at, b.id
    limit 1
    for update of b;
    if found then
      cap := (select max((v ->> 'boostBp')::int) from jsonb_each(public.gear_rules() -> 'fuel' -> 'items') x(k, v));
      update public.user_boosts
        set workout_id = new.id, expires_at = greatest(now(), gel.started_at + interval '1 millisecond')
        where id = gel.id;
      new.boost := jsonb_set(new.boost, '{gel_bp}',
        to_jsonb(least(cap, (new.boost ->> 'gel_bp')::int + round((gel.multiplier - 1) * 10000)::int)));
    end if;
  end if;
  return new;
end;
$$;
revoke execute on function public.workouts_stamp_boost() from public, anon, authenticated;

