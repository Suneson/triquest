function toPath(bitmap) {
  const rows = bitmap.trim().split('\n').map((r) => r.trim());
  let d = '';
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') { x++; continue; }
      const start = x;
      while (x < row.length && row[x] === '#') x++;
      d += `M${start} ${y}h${x - start}v1h-${x - start}z`;
    }
  });
  return d;
}

const P = Object.fromEntries(Object.entries(B).map(([k, v]) => [k, toPath(v)]));

export const ICON_NAMES = Object.keys(P);

export function svg(name, cls = '') {
  return `<svg viewBox="0 0 16 16" class="ic ${cls}" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true"><path d="${P[name] || P.other}"/></svg>`;
}

