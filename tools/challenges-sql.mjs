// challenges-sql.mjs — writes the generated part of supabase/migrations/0019_challenges.sql
// (the challenge rules) from js/core/challenges.js, so the two can't drift.
// tests/challenges-sql.test.js fails if the file and this disagree.
//
//   node tools/challenges-sql.mjs          rewrite the block in place
//   node tools/challenges-sql.mjs --print  print it

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { CHALLENGE_RULES, KINDS, LOWER_WINS } from '../js/core/challenges.js';

export const MIGRATION = fileURLToPath(new URL('../supabase/migrations/0019_challenges.sql', import.meta.url));
export const BEGIN = '-- BEGIN GENERATED by tools/challenges-sql.mjs from js/core/challenges.js — do not edit by hand';
export const END = '-- END GENERATED';

export function generatedBlock() {
  const rules = JSON.stringify({ ...CHALLENGE_RULES, kinds: KINDS, lowerWins: [...LOWER_WINS] }).replace(/'/g, "''");
  return [
    BEGIN,
    'create or replace function public.challenge_rules()',
    'returns jsonb language sql immutable set search_path = public as $$',
    `  select '${rules}'::jsonb;`,
    '$$;',
    END,
  ].join('\n');
}

export function withBlock(sql) {
  const a = sql.indexOf(BEGIN);
  const b = sql.indexOf(END);
  if (a < 0 || b < a) throw new Error('0019_challenges.sql has no generated block markers');
  return sql.slice(0, a) + generatedBlock() + sql.slice(b + END.length);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes('--print')) console.log(generatedBlock());
  else {
    writeFileSync(MIGRATION, withBlock(readFileSync(MIGRATION, 'utf8')));
    console.log('wrote the generated block of', MIGRATION);
  }
}
