-- Everyone who joined, their score now and their place (ties share it; no-shows last).
create or replace function public.challenge_standings(p_id uuid)
returns table (user_id uuid, display_name text, avatar text, score bigint, place bigint, cut boolean)
language plpgsql stable security definer set search_path = public as $$
declare c public.challenges;
begin
  if not public.challenge_visible(p_id) then raise exception 'ch:not_found' using errcode = '22023'; end if;
  select * into c from public.challenges where id = p_id;
  return query
    with s as (
      select p.user_id, sc.score, sc.cut
      from public.challenge_participants p, public.challenge_score(c, p.user_id) sc
      where p.challenge_id = p_id and p.status = 'joined'
    )
    select s.user_id, coalesce(pf.display_name, 'Athlete'), pf.settings ->> 'avatar', s.score,
           case when s.score is null then null
                when (public.challenge_rules() -> 'lowerWins') ? c.kind then rank() over (order by s.score asc nulls last)
                else rank() over (order by s.score desc nulls last) end,
           s.cut
    from s left join public.profiles pf on pf.id = s.user_id
    order by 5 nulls last, 1;
end;
$$;

