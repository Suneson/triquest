-- ---- the guards (stakeBlock() in challenges.js) -------------------------------------------

-- Why this athlete can't stake p_stake now, or null: age | verified | balance | share | week | pair
create or replace function public.stake_block(p_user uuid, p_stake int, p_others uuid[])
returns text language plpgsql stable security definer set search_path = public as $$
declare
  cr jsonb := public.challenge_rules();
  bal bigint;
  week bigint;
  o uuid;
begin
  if p_stake <= 0 then return null; end if;
  if (select now() - created_at from auth.users where id = p_user) < make_interval(days => (cr ->> 'minAccountDays')::int) then
    return 'age';
  end if;
  if (select count(*) from public.workouts w
      where w.user_id = p_user and w.date >= current_date - 30 and public.proof_of(w) = 'strava' and public.earns(w))
     < (cr ->> 'minVerified')::int then
    return 'verified';
  end if;
  select f.coins into bal from public.wallet_fold(p_user) f;
  if p_stake > bal then return 'balance'; end if;
  if p_stake::numeric * 10000 > bal * (cr ->> 'maxStakeShareBp')::numeric then return 'share'; end if;
  select coalesce(-sum(m.coins), 0) into week from public.coin_moves m join public.challenges c on c.id = m.challenge_id
    where m.user_id = p_user and m.kind = 'stake' and m.created_at > now() - interval '7 days' and c.state <> 'cancelled';
  if week + p_stake > (cr ->> 'weeklyStakeCap')::int then return 'week'; end if;
  foreach o in array coalesce(p_others, '{}') loop
    if o = p_user then continue; end if;
    if (select count(*) from public.challenges c
        where c.stake > 0 and c.state <> 'cancelled' and c.created_at > now() - interval '7 days'
          and exists (select 1 from public.challenge_participants a where a.challenge_id = c.id and a.user_id = p_user and a.status = 'joined')
          and exists (select 1 from public.challenge_participants b where b.challenge_id = c.id and b.user_id = o and b.status = 'joined'))
       >= (cr ->> 'pairWeek')::int
    or (select count(*) from public.challenges c
        where c.stake > 0 and c.state <> 'cancelled' and c.created_at > now() - interval '30 days'
          and exists (select 1 from public.challenge_participants a where a.challenge_id = c.id and a.user_id = p_user and a.status = 'joined')
          and exists (select 1 from public.challenge_participants b where b.challenge_id = c.id and b.user_id = o and b.status = 'joined'))
       >= (cr ->> 'pairMonth')::int then
      return 'pair';
    end if;
  end loop;
  return null;
end;
$$;

