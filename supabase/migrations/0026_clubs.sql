-- ---- totals: verified work only, never anyone's days ------------------------------------------

-- the members' verified minutes in a week (Monday), counted while they were in the club
create or replace function public.club_week_minutes(p_club bigint, p_week date)
returns int language sql stable security definer set search_path = public as $$
  select coalesce(floor(sum(greatest(coalesce((w.actual ->> 'durationMin')::numeric, w.duration_min, 0), 0))), 0)::int
  from public.club_members m
  join public.workouts w on w.user_id = m.user_id
  where m.club_id = p_club
    and w.date between p_week and p_week + 6
    and w.date >= (m.joined_at at time zone 'utc')::date
    and (m.left_at is null or w.date <= (m.left_at at time zone 'utc')::date)
    and public.earns(w);
$$;

-- the members' verified kilometres (run, ride, swim, brick) since a relay started
create or replace function public.club_relay_km(p_club bigint, p_since timestamptz)
returns numeric language sql stable security definer set search_path = public as $$
  select coalesce(round(sum(greatest(coalesce((w.actual ->> 'distanceKm')::numeric, w.distance_km, 0), 0)), 1), 0)
  from public.club_members m
  join public.workouts w on w.user_id = m.user_id
  where m.club_id = p_club
    and w.type in ('run', 'bike', 'swim', 'brick')
    and w.date >= (greatest(p_since, m.joined_at) at time zone 'utc')::date
    and (m.left_at is null or w.date <= (m.left_at at time zone 'utc')::date)
    and public.earns(w);
$$;

