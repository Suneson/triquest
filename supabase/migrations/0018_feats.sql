-- A session as feats see it (distM, movingSec … in js/core/feats.js). The
-- engine holds one athlete's history as an array of these: no temp tables.
create type public.feat_row as (
  id text, date date, type text, ord text, start_ts timestamptz,
  dist_m numeric, mov numeric, el numeric, vmax numeric, sport_type text,
  manual boolean, trainer boolean, earns boolean, strava boolean, rest boolean,
  elev numeric, best jsonb, segs jsonb, wtype int, source text, extra jsonb, exercises jsonb
);

create or replace function public.feat_base(p_user uuid)
returns table (
  id text, date date, type text, ord text, start_ts timestamptz,
  dist_m numeric, mov numeric, el numeric, vmax numeric, sport_type text,
  manual boolean, trainer boolean, earns boolean, strava boolean, rest boolean,
  elev numeric, best jsonb, segs jsonb, wtype int, source text, extra jsonb, exercises jsonb
) language sql stable set search_path = public as $$
  with x as (
    select w as wr, w.*, coalesce(w.actual, '{}'::jsonb) as a,
           case when jsonb_typeof(w.actual -> 'distanceM') = 'number' then (w.actual ->> 'distanceM')::numeric end as a_m,
           case when jsonb_typeof(w.actual -> 'distanceKm') = 'number' then (w.actual ->> 'distanceKm')::numeric end as a_km,
           case when jsonb_typeof(w.actual -> 'movingSec') = 'number' then (w.actual ->> 'movingSec')::numeric end as a_mov,
           case when jsonb_typeof(w.actual -> 'durationMin') = 'number' then (w.actual ->> 'durationMin')::numeric end as a_min,
           case when jsonb_typeof(w.actual -> 'elapsedSec') = 'number' then (w.actual ->> 'elapsedSec')::numeric end as a_el
    from public.workouts w where w.user_id = p_user
  )
  select x.id, x.date, x.type,
         coalesce(x.a ->> 'startUtc', to_char(x.completed_at at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'), ''),
         case when x.a ->> 'startUtc' ~ '^\d{4}-\d{2}-\d{2}T' then (x.a ->> 'startUtc')::timestamptz end,
         coalesce(case when x.a_m > 0 then x.a_m end, case when x.a_km > 0 then x.a_km * 1000 end,
                  case when x.distance_km > 0 then x.distance_km * 1000 end, 0),
         coalesce(case when x.a_mov > 0 then x.a_mov end, case when x.a_min > 0 then x.a_min * 60 end,
                  case when x.duration_min > 0 then x.duration_min * 60 end, 0),
         coalesce(nullif(x.a_el, 0),
                  case when x.a_mov > 0 then x.a_mov end, case when x.a_min > 0 then x.a_min * 60 end,
                  case when x.duration_min > 0 then x.duration_min * 60 end, 0),
         coalesce(case when jsonb_typeof(x.a -> 'maxSpeedKmh') = 'number' then (x.a ->> 'maxSpeedKmh')::numeric end, 0),
         coalesce(x.a ->> 'sportType', case x.type when 'run' then 'Run' when 'bike' then 'Ride' when 'swim' then 'Swim' end),
         coalesce((x.a ->> 'manual')::boolean, false),
         coalesce((x.a ->> 'trainer')::boolean, false),
         public.earns(x.wr),
         x.strava_activity_id is not null or x.source = 'strava',
         coalesce(x.on_rest_day, public.is_rest_day(p_user, x.date)),
         round(coalesce(case when jsonb_typeof(x.a -> 'elevationGainM') = 'number' then (x.a ->> 'elevationGainM')::numeric end, 0)),
         coalesce(x.a -> 'bestEfforts', '{}'::jsonb),
         case when jsonb_typeof(x.a -> 'segments') = 'array' then x.a -> 'segments' else '[]'::jsonb end,
         case when jsonb_typeof(x.a -> 'workoutType') = 'number' then (x.a ->> 'workoutType')::int end,
         x.source, coalesce(x.extra, '{}'::jsonb),
         case when jsonb_typeof(x.exercises) = 'array' then x.exercises else '[]'::jsonb end
  from x;
$$;

-- baseReason(): since | manual | proof | machine | restDay, or null.
create or replace function public.feat_base_reason(p_date date, p_manual boolean, p_earns boolean, p_strava boolean,
    p_trainer boolean, p_sport_type text, p_rest boolean, p_sport text)
returns text language sql stable set search_path = public as $$
  select case
    when p_date < (public.feat_rules() ->> 'since')::date then 'since'
    when p_manual then 'manual'
    when not p_earns or not p_strava then 'proof'
    when public.feat_rules() -> 'sportTypes' ? p_sport
         and (p_trainer or not coalesce(public.feat_rules() -> 'sportTypes' -> p_sport ? p_sport_type, false)) then 'machine'
    when p_rest then 'restDay'
  end;
$$;

-- sessionBound(): maxSpeed | tooFast | tooSlow | tooLong, or null.
create or replace function public.feat_bound(p_sport text, m numeric, mov numeric, vmax numeric)
returns text language sql stable set search_path = public as $$
  with r as (select public.feat_rules() as j)
  select case
    when p_sport = 'run' and vmax > (r.j ->> 'runMaxSpeedKmh')::numeric then 'maxSpeed'
    when p_sport = 'run' and m >= 21000 and mov > 0 and mov / (m / 1000) < (r.j ->> 'runFastestSecPerKm')::numeric then 'tooFast'
    when p_sport = 'run' and m >= 21000 and mov > 0 and mov / (m / 1000) > (r.j ->> 'runSlowestSecPerKm')::numeric then 'tooSlow'
    when p_sport = 'bike' and vmax > (r.j ->> 'bikeMaxSpeedKmh')::numeric then 'maxSpeed'
    when p_sport = 'bike' and m >= 50000 and mov > 0 and m / mov * 3.6 > (r.j ->> 'bikeMaxAvgKmh')::numeric then 'tooFast'
    when p_sport = 'swim' and m > (r.j ->> 'swimMaxM')::numeric then 'tooLong'
    when p_sport = 'swim' and m >= (r.j ->> 'swimFastestMinM')::numeric and mov > 0
         and mov / (m / 100) < (r.j ->> 'swimFastestSecPer100')::numeric then 'tooFast'
  end from r;
$$;

-- Every award and rejection a history earns (evaluateFeats() in feats.js).
create or replace function public.feat_eval(p_user uuid)
returns table (out_kind text, feat_id text, season text, workout_id text, value numeric,
               achieved_on date, whole boolean, logged boolean, reason text)
language plpgsql volatile set search_path = public as $$
#variable_conflict use_column
declare
  rules jsonb := public.feat_rules();
  since date := (rules ->> 'since')::date;
  f public.feats;
  p jsonb;
  b record;
  v numeric; hit boolean; why text; wh boolean; done boolean;
  d numeric;
  seasons text[];
  bw numeric; top numeric; best_reps int; prev_best numeric; n_earlier int;
  lib text;
  cnt int;
  wrec record;
  dt date;
  ps record; pb record; pr record;
  ov boolean;
  sea text;
  fb public.feat_row[];
begin
  fb := array(select row(x.*)::public.feat_row from public.feat_base(p_user) x);

  for f in select * from public.feats order by ord loop
    p := f.params;

    if f.kind in ('distance', 'time', 'climb', 'speed', 'segment', 'steady', 'pace') then
      done := false;
      for b in select * from unnest(fb) where type = f.sport order by date, ord collate "C", id collate "C" loop
        v := 0; hit := false; why := null; wh := false;
        if f.kind = 'distance' then
          v := round(b.dist_m) / 1000.0;
          hit := b.dist_m >= (p ->> 'km')::numeric * 1000;
        elsif f.kind = 'time' then
          d := case p ->> 'dist' when '5k' then 5000 when '10k' then 10000 end;
          if coalesce((b.best ->> (p ->> 'dist'))::numeric, 0) > 0 then v := (b.best ->> (p ->> 'dist'))::numeric;
          elsif b.dist_m >= d and b.mov > 0 then v := round(b.mov * d / b.dist_m); wh := true;
          else v := 0; end if;
          hit := v > 0 and v <= (p ->> 'sec')::numeric;
          if hit and v < (rules -> 'runFastestPace' ->> (p ->> 'dist'))::numeric then why := 'tooFast'; end if;
        elsif f.kind = 'climb' then
          v := b.elev;
          hit := v >= (p ->> 'm')::numeric;
          if hit and (case when b.dist_m < (rules ->> 'climbMinKm')::numeric * 1000 then true
                           else v / (b.dist_m / 1000) > (rules ->> 'climbMaxMPerKm')::numeric end) then why := 'climbDensity'; end if;
        elsif f.kind = 'speed' then
          v := case when b.dist_m >= (p ->> 'km')::numeric * 1000 and b.mov > 0 then round(b.dist_m / b.mov * 36) / 10.0 else 0 end;
          hit := v >= (p ->> 'kmh')::numeric;
          wh := true;
          if hit and v > (rules ->> 'bikeMaxAvgKmhShort')::numeric then why := 'tooFast'; end if;
        elsif f.kind = 'segment' then
          select coalesce(max(coalesce((s ->> 'gainM')::numeric, 0)), 0), count(*) > 0,
                 count(*) filter (where not (coalesce((s ->> 'gainM')::numeric, 0) > 0 and coalesce((s ->> 'sec')::numeric, 0) > 0
                   and (s ->> 'gainM')::numeric / ((s ->> 'sec')::numeric / 3600) > (rules ->> 'maxVamMh')::numeric)) = 0
            into v, hit, ov
            from jsonb_array_elements(b.segs) s
            where coalesce((s ->> 'cat')::numeric, 0) >= (p ->> 'cat')::numeric;
          if hit and ov then why := 'vam'; end if;
        elsif f.kind = 'steady' then
          v := case when b.dist_m >= (p ->> 'm')::numeric and b.mov > 0 then round(b.el / b.mov * 100) / 100.0 else 0 end;
          hit := v > 0 and v <= (p ->> 'ratio')::numeric;
        elsif f.kind = 'pace' then
          v := case when b.dist_m >= (p ->> 'm')::numeric and b.mov > 0 then round(b.mov / (b.dist_m / 100)) else 0 end;
          hit := v > 0 and v <= (p ->> 'sec')::numeric;
          wh := true;
        end if;
        if not hit then continue; end if;
        if why is null then
          why := coalesce(public.feat_base_reason(b.date, b.manual, b.earns, b.strava, b.trainer, b.sport_type, b.rest, f.sport),
                          public.feat_bound(f.sport, b.dist_m, b.mov, b.vmax));
        end if;
        if why is not null then
          if why <> 'since' then
            return query select 'reject'::text, f.id, null::text, b.id, null::numeric, null::date, false, false, why;
          end if;
          continue;
        end if;
        if not done then
          return query select 'award'::text, f.id, public.feat_season(b.date), b.id, v, b.date, wh, false, null::text;
          done := true;
        end if;
      end loop;

    elsif f.kind = 'month' then
      seasons := '{}';
      for b in
        with ok as (
          select * from unnest(fb)
          where type = f.sport
            and public.feat_base_reason(date, manual, earns, strava, trainer, sport_type, rest, f.sport) is null
            and public.feat_bound(f.sport, dist_m, mov, vmax) is null
        ),
        days as (
          select date, least((rules -> 'dayCapKm' ->> f.sport)::numeric * 1000, sum(dist_m)) as m,
                 (array_agg(id order by ord collate "C", id collate "C"))[count(*)::int] as last_id
          from ok group by date
        ),
        run as (
          select date, last_id, to_char(date, 'YYYY-MM') as mo,
                 sum(m) over (partition by to_char(date, 'YYYY-MM') order by date) as cum,
                 sum(m) over (partition by to_char(date, 'YYYY-MM')) as total
          from days
        ),
        hits as (
          select distinct on (mo) mo, date, last_id, total from run
          where cum >= (p ->> 'km')::numeric * 1000 order by mo, date
        )
        select * from hits order by mo
      loop
        sea := public.feat_season(b.date);
        if sea = any(seasons) then continue; end if;
        seasons := seasons || sea;
        return query select 'award'::text, f.id, sea, b.last_id, round(b.total) / 1000.0, b.date, false, false, null::text;
      end loop;

    elsif f.kind = 'count' then
      select * into b from (
        select *, row_number() over (order by date, ord collate "C", id collate "C") as rn from unnest(fb)
        where type = 'gym' and earns and date >= since and not rest
      ) q where rn = (p ->> 'n')::int;
      if found then
        return query select 'award'::text, f.id, public.feat_season(b.date), b.id, (p ->> 'n')::numeric, b.date, false, false, null::text;
      end if;

    elsif f.kind = 'lift' then
      lib := rules -> 'lifts' ->> (p ->> 'lift');
      for b in select * from unnest(fb) where type = 'gym' and earns and date >= since order by date, ord collate "C", id collate "C" loop
        select max(kg) into top from public.feat_lift_sets(b.exercises, lib)
          where reps between (rules -> 'liftReps' ->> 0)::int and (rules -> 'liftReps' ->> 1)::int;
        if top is null then continue; end if;
        bw := public.feat_bodyweight(p_user, b.date);
        if bw is null or top < (p ->> 'ratio')::numeric * bw then continue; end if;
        select max(reps) into best_reps from public.feat_lift_sets(b.exercises, lib) where kg = top
          and reps between (rules -> 'liftReps' ->> 0)::int and (rules -> 'liftReps' ->> 1)::int;
        select count(*) into n_earlier from unnest(fb) x
          where x.type = 'gym' and (x.date, x.ord collate "C", x.id collate "C") < (b.date, b.ord collate "C", b.id collate "C")
            and exists (select 1 from public.feat_lift_sets(x.exercises, lib));
        select coalesce(max(case when s.reps = 1 then s.kg else s.kg * (1 + s.reps / 30.0) end), 0) into prev_best
          from unnest(fb) x, public.feat_lift_sets(x.exercises, lib) s
          where x.type = 'gym' and (x.date, x.ord collate "C", x.id collate "C") < (b.date, b.ord collate "C", b.id collate "C")
            and x.date >= b.date - (rules ->> 'liftJumpDays')::int and s.reps <= 12;
        why := case
          when b.rest then 'restDay'
          when not coalesce((b.extra ->> 'gymCheckin')::boolean, false) then 'noCheckin'
          when top > (rules -> 'liftMaxRatio' ->> (p ->> 'lift'))::numeric * bw then 'liftRatio'
          when n_earlier < (rules ->> 'liftMinHistory')::int then 'liftHistory'
          when (case when best_reps = 1 then top else top * (1 + best_reps / 30.0) end) > (rules ->> 'liftJump')::numeric * prev_best then 'liftJump'
        end;
        if why is not null then
          return query select 'reject'::text, f.id, null::text, b.id, null::numeric, null::date, false, false, why;
          continue;
        end if;
        return query select 'award'::text, f.id, public.feat_season(b.date), b.id, top, b.date, false, true, null::text;
        exit;
      end loop;

    elsif f.kind = 'weeks' then
      for wrec in
        with ok as (
          select *, date_trunc('week', date)::date as wk from unnest(fb)
          where type in ('run', 'bike', 'swim', 'gym')
            and case when type = 'gym' then earns and date >= since and not rest
                     else public.feat_base_reason(date, manual, earns, strava, trainer, sport_type, rest, type) is null end
        ),
        firsts as (
          select distinct on (wk, type) wk, type, id, date, ord from ok order by wk, type, date, ord collate "C", id collate "C"
        ),
        complete as (
          select wk, (array_agg(id order by date, ord collate "C", id collate "C"))[4] as last_id,
                 (array_agg(date order by date, ord collate "C", id collate "C"))[4] as last_date
          from firsts group by wk having count(*) = 4
        )
        select c.* from complete c
        where (select count(*) from complete c2 where c2.wk > c.wk - 7 * (p ->> 'n')::int and c2.wk <= c.wk) = (p ->> 'n')::int
        order by c.wk limit 1
      loop
        return query select 'award'::text, f.id, public.feat_season(wrec.last_date), wrec.last_id, (p ->> 'n')::numeric, wrec.last_date, false, false, null::text;
      end loop;

    elsif f.kind = 'triday' then
      for dt in select distinct date from unnest(fb) order by date loop
        select * into ps from public.feat_tri_pick(fb, dt, 'swim', (p ->> 'swim')::numeric);
        select * into pb from public.feat_tri_pick(fb, dt, 'bike', (p ->> 'bike')::numeric);
        select * into pr from public.feat_tri_pick(fb, dt, 'run', (p ->> 'run')::numeric);
        if ps.id is null or pb.id is null or pr.id is null then continue; end if;
        ov := ps.start_ts is not null and pb.start_ts is not null and pr.start_ts is not null and (
              (ps.start_ts < pb.start_ts + make_interval(secs => pb.el) and pb.start_ts < ps.start_ts + make_interval(secs => ps.el))
           or (ps.start_ts < pr.start_ts + make_interval(secs => pr.el) and pr.start_ts < ps.start_ts + make_interval(secs => ps.el))
           or (pb.start_ts < pr.start_ts + make_interval(secs => pr.el) and pr.start_ts < pb.start_ts + make_interval(secs => pb.el)));
        if ov then
          return query select 'reject'::text, f.id, null::text, pr.id, null::numeric, null::date, false, false, 'overlap'::text;
          continue;
        end if;
        select q.id into sea from (values (ps.id, ps.ord), (pb.id, pb.ord), (pr.id, pr.ord)) q(id, ord)
          order by q.ord collate "C" desc, q.id collate "C" desc limit 1;
        return query select 'award'::text, f.id, public.feat_season(dt), sea, null::numeric, dt, false, false, null::text;
        exit;
      end loop;

    elsif f.kind = 'race' then
      seasons := '{}';
      for b in
        select x.* from unnest(fb) x
        where ((x.type = 'run' and x.wtype = 1) or (x.type = 'bike' and x.wtype = 11))
          and (exists (select 1 from unnest(fb) y where y.date = x.date and coalesce((y.extra ->> 'isRace')::boolean, false)
                                             and y.source is distinct from 'strava')
               or exists (select 1 from public.profiles pf, jsonb_array_elements(
                            case when jsonb_typeof(pf.settings -> 'events') = 'array' then pf.settings -> 'events' else '[]'::jsonb end) e
                          where pf.id = p_user and e ->> 'date' = x.date::text))
          and x.dist_m >= (case when x.type = 'run' then (p ->> 'runKm')::numeric else (p ->> 'bikeKm')::numeric end) * 1000
        order by x.date, x.ord collate "C", x.id collate "C"
      loop
        why := coalesce(public.feat_base_reason(b.date, b.manual, b.earns, b.strava, b.trainer, b.sport_type, b.rest, b.type),
                        public.feat_bound(b.type, b.dist_m, b.mov, b.vmax));
        if why is not null and why <> 'restDay' then
          if why <> 'since' then
            return query select 'reject'::text, f.id, null::text, b.id, null::numeric, null::date, false, false, why;
          end if;
          continue;
        end if;
        sea := public.feat_season(b.date);
        if sea = any(seasons) then continue; end if;
        seasons := seasons || sea;
        return query select 'award'::text, f.id, sea, b.id, round(b.dist_m) / 1000.0, b.date, false, false, null::text;
      end loop;
    end if;
  end loop;
end;
$$;

create or replace function public.feat_season(p_date date)
returns text language sql immutable set search_path = public as $$
  select extract(year from p_date)::int || '-Q' || extract(quarter from p_date)::int;
$$;

-- Done working sets of one library lift: (kg, reps).
create or replace function public.feat_lift_sets(p_exercises jsonb, p_lib text)
returns table (kg numeric, reps int) language sql immutable set search_path = public as $$
  select (st ->> 'weight')::numeric, (st ->> 'reps')::numeric::int
  from jsonb_array_elements(p_exercises) ex,
       jsonb_array_elements(case when jsonb_typeof(ex -> 'sets') = 'array' then ex -> 'sets' else '[]'::jsonb end) st
  where ex ->> 'libId' = p_lib
    and coalesce(st ->> 'done', 'false') = 'true'
    and coalesce(st ->> 'kind', 'work') <> 'warmup'
    and jsonb_typeof(st -> 'weight') = 'number' and (st ->> 'weight')::numeric > 0
    and jsonb_typeof(st -> 'reps') = 'number' and (st ->> 'reps')::numeric > 0;
$$;

-- bodyweightAt(): the heaviest weight logged in the 30 days up to a date.
create or replace function public.feat_bodyweight(p_user uuid, p_date date)
returns numeric language sql stable set search_path = public as $$
  select max((m ->> 'weight')::numeric)
  from public.profiles pf,
       jsonb_array_elements(case when jsonb_typeof(pf.settings -> 'bodyMetrics') = 'array' then pf.settings -> 'bodyMetrics' else '[]'::jsonb end) m
  where pf.id = p_user
    and m ->> 'date' <= p_date::text
    and m ->> 'date' >= (p_date - (public.feat_rules() ->> 'bodyweightDays')::int)::text
    and jsonb_typeof(m -> 'weight') = 'number' and (m ->> 'weight')::numeric > 0;
$$;

-- One sport's longest qualifying session on a day, if it reaches the distance.
create or replace function public.feat_tri_pick(p_fb public.feat_row[], p_date date, p_sport text, p_km numeric)
returns table (id text, ord text, start_ts timestamptz, el numeric)
language sql stable set search_path = public as $$
  select q.id, q.ord, q.start_ts, q.el from (
    select * from unnest(p_fb) x
    where x.date = p_date and x.type = p_sport
      and public.feat_base_reason(x.date, x.manual, x.earns, x.strava, x.trainer, x.sport_type, x.rest, p_sport) is null
      and public.feat_bound(p_sport, x.dist_m, x.mov, x.vmax) is null
    order by x.dist_m desc, x.date, x.ord collate "C", x.id collate "C" limit 1
  ) q where q.dist_m >= p_km * 1000;
$$;

-- Write what's new: awards (once per feat, or per season) and rejections.
-- Runs after a Strava sync and from the trophy case; idempotent.
create or replace function public.award_feats(p_user uuid default auth.uid())
returns setof public.user_feats language plpgsql security definer set search_path = public as $$
begin
  if p_user is null then raise exception 'not signed in' using errcode = '28000'; end if;
  if p_user <> coalesce(auth.uid(), p_user) then raise exception 'not yours' using errcode = '42501'; end if;
  perform pg_advisory_xact_lock(hashtext('feats:' || p_user::text));
  return query
    with e as materialized (select * from public.feat_eval(p_user)),
    rej as (
      insert into public.feat_rejections (user_id, feat_id, workout_id, reason)
      select distinct p_user, e.feat_id, e.workout_id, e.reason from e where e.out_kind = 'reject'
      on conflict (user_id, feat_id, workout_id) do update set reason = excluded.reason
    )
    insert into public.user_feats (user_id, feat_id, season, workout_id, value, whole, logged, achieved_on)
    select p_user, e.feat_id,
           -- a one-off feat is one row ever; its season is the one it was won in
           e.season, e.workout_id, e.value, e.whole, e.logged, e.achieved_on
    from e join public.feats f on f.id = e.feat_id
    where e.out_kind = 'award'
      and (f.repeatable or not exists (select 1 from public.user_feats u where u.user_id = p_user and u.feat_id = e.feat_id))
    on conflict (user_id, feat_id, season) do nothing
    returning *;
end;
$$;
grant execute on function public.award_feats(uuid) to authenticated, service_role;
revoke execute on function public.feat_eval(uuid) from public, anon, authenticated;
