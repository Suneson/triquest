create table if not exists public.workshop_jobs (
  id           bigint generated always as identity primary key,
  user_id      uuid not null references auth.users (id) on delete cascade,
  item_id      text not null references public.gear_catalog (id),
  spend_id     bigint references public.coin_spends (id),
  cost         int not null,
  bay          int not null,
  queued_at    timestamptz not null default now(),
  started_at   timestamptz not null,
  finishes_at  timestamptz not null,
  state        text not null default 'queued' check (state in ('queued', 'done', 'cancelled')),
  skipped_with text,
  cancelled_at timestamptz,
  midfit       boolean not null default false,
  refund       int not null default 0,
  check (finishes_at >= started_at)
);
create index if not exists workshop_jobs_user on public.workshop_jobs (user_id, state);
alter table public.workshop_jobs enable row level security;
create policy workshop_jobs_own on public.workshop_jobs for select using (user_id = auth.uid());
grant select on public.workshop_jobs to authenticated;

-- ---- the rules ---------------------------------------------------------------------

-- fitMinutes(): a gear tier by its tier, a prop its own; null when not fitted
create or replace function public.workshop_fit_min(p_item text)
returns int language sql stable set search_path = public as $$
  select case
    when c.kind = 'gear' and c.tier > 0 then (public.workshop_rules() -> 'fitMin' ->> c.tier)::int
    when c.kind = 'prop' then (public.workshop_rules() -> 'props' -> c.id ->> 'fitMin')::int
  end
  from public.gear_catalog c where c.id = p_item;
$$;

-- bayCount()
create or replace function public.workshop_bays(p_user uuid)
returns int language sql stable set search_path = public as $$
  select (public.workshop_rules() ->> 'bays')::int
       + case when exists (select 1 from public.user_feats f where f.user_id = p_user and f.feat_id = public.workshop_rules() ->> 'bay2Feat')
              then 1 else 0 end;
$$;

-- fuel bought and not used: taken as a boost, or spent finishing a job
create or replace function public.fuel_held(p_user uuid, p_kind text)
returns bigint language sql stable set search_path = public as $$
  select (select count(*) from public.coin_spends s where s.user_id = p_user and s.item_id = p_kind)
       - (select count(*) from public.user_boosts b where b.user_id = p_user and b.kind = p_kind)
       - (select count(*) from public.workshop_jobs j where j.user_id = p_user and j.skipped_with = p_kind);
$$;

-- ---- owning what's finished --------------------------------------------------------

-- a finished job counts from its finish even before it's settled
create or replace function public.gear_bp_sport(p_user uuid, p_sport text, p_at timestamptz)
returns int language sql stable set search_path = public as $$
  select least((public.gear_rules() ->> 'sportCapBp')::int, coalesce(sum(c.boost_bp), 0))::int
  from (
    select c.slot, max(c.tier) as tier
    from (
      select g.item_id from public.user_gear g where g.user_id = p_user and g.acquired_at <= p_at
      union
      select j.item_id from public.workshop_jobs j where j.user_id = p_user and j.state <> 'cancelled' and j.finishes_at <= p_at
    ) o join public.gear_catalog c on c.id = o.item_id
    where c.kind = 'gear' and c.sport = p_sport
    group by c.slot
  ) o
  join public.gear_catalog c on c.kind = 'gear' and c.sport = p_sport and c.slot = o.slot and c.tier = o.tier;
$$;

-- every finished job becomes inventory, owned from its finish time
create or replace function public.workshop_settle(p_user uuid)
returns int language plpgsql security definer set search_path = public as $$
declare n int;
begin
  insert into public.user_gear (user_id, item_id, acquired_at)
  select j.user_id, j.item_id, j.finishes_at from public.workshop_jobs j
  where j.user_id = p_user and j.state = 'queued' and j.finishes_at <= now()
  on conflict (user_id, item_id) do nothing;
  update public.workshop_jobs set state = 'done' where user_id = p_user and state = 'queued' and finishes_at <= now();
  get diagnostics n = row_count;
  return n;
end;
$$;

-- reflow(): the jobs waiting in a bay move up behind whatever is being fitted
create or replace function public.workshop_reflow(p_user uuid, p_bay int)
returns void language plpgsql security definer set search_path = public as $$
declare
  cursor_at timestamptz;
  j record;
  len interval;
begin
  select greatest(now(), coalesce(max(finishes_at), now())) into cursor_at from public.workshop_jobs
  where user_id = p_user and bay = p_bay and state = 'queued' and started_at <= now() and finishes_at > now();
  for j in
    select id, started_at, finishes_at from public.workshop_jobs
    where user_id = p_user and bay = p_bay and state = 'queued' and started_at > now()
    order by started_at, id
  loop
    len := j.finishes_at - j.started_at;
    update public.workshop_jobs set started_at = cursor_at, finishes_at = cursor_at + len where id = j.id;
    cursor_at := cursor_at + len;
  end loop;
end;
$$;

-- ---- buying: gear and props go to the workshop ---------------------------------------

create or replace function public.buy_gear(p_item_id text)
returns json language plpgsql security definer set search_path = public as $$
declare
  uid  uuid := auth.uid();
  c    public.gear_catalog;
  bal  bigint;
  sid  bigint;
  mins int;
  pick record;
begin
  if uid is null then raise exception 'gear:not_signed_in' using errcode = '28000'; end if;
  perform pg_advisory_xact_lock(hashtext('gear:' || uid::text));
  perform public.workshop_settle(uid);
  select * into c from public.gear_catalog where id = p_item_id;
  if not found then raise exception 'gear:unknown_item' using errcode = '22023'; end if;
  if c.kind in ('gear', 'prop', 'kit') then
    if c.kind = 'gear' and c.tier = 0 then raise exception 'gear:starter' using errcode = '22023'; end if;
    if exists (select 1 from public.user_gear where user_id = uid and item_id = c.id) then
      raise exception 'gear:owned' using errcode = '22023';
    end if;
    if exists (select 1 from public.workshop_jobs where user_id = uid and item_id = c.id and state = 'queued') then
      raise exception 'gear:in_workshop' using errcode = '22023';
    end if;
    -- the tier below must be owned or already in the workshop ahead of it
    if c.kind = 'gear' and c.tier > 1 and not exists (
      select 1 from public.gear_catalog p
      where p.kind = 'gear' and p.sport = c.sport and p.slot = c.slot and p.tier = c.tier - 1
        and (exists (select 1 from public.user_gear g where g.user_id = uid and g.item_id = p.id)
          or exists (select 1 from public.workshop_jobs j where j.user_id = uid and j.item_id = p.id and j.state = 'queued'))
    ) then
      raise exception 'gear:tier_locked' using errcode = '22023';
    end if;
  else -- fuel
    if public.fuel_held(uid, c.id) >= (public.gear_rules() -> 'fuel' -> 'items' -> c.id ->> 'maxHeld')::int then
      raise exception 'gear:fuel_full' using errcode = '22023';
    end if;
  end if;
  select case when c.currency = 'carbs' then f.carbs else f.coins end into bal from public.wallet_fold(uid) f;
  if bal < c.cost then raise exception 'gear:insufficient' using errcode = '22023'; end if;
  insert into public.coin_spends (user_id, item_id, coins, currency) values (uid, c.id, c.cost, c.currency) returning id into sid;
  if c.kind = 'kit' then
    insert into public.user_gear (user_id, item_id) values (uid, c.id);
  elsif c.kind in ('gear', 'prop') then
    mins := public.workshop_fit_min(c.id);
    -- placeJob(): the bay that frees up first (lowest number on a tie), from then or now
    select b.bay, greatest(now(), coalesce(max(j.finishes_at), now())) as start_at into pick
    from generate_series(1, public.workshop_bays(uid)) b(bay)
    left join public.workshop_jobs j on j.user_id = uid and j.bay = b.bay and j.state = 'queued' and j.finishes_at > now()
    group by b.bay
    order by 2, 1
    limit 1;
    insert into public.workshop_jobs (user_id, item_id, spend_id, cost, bay, started_at, finishes_at)
    values (uid, c.id, sid, c.cost, pick.bay, pick.start_at, pick.start_at + make_interval(mins => mins));
  end if;
  return public.wallet_for(uid);
end;
$$;

-- ---- cancelling, and finishing with a gel -----------------------------------------------

create or replace function public.workshop_cancel(p_job bigint)
returns json language plpgsql security definer set search_path = public as $$
declare
  uid uuid := auth.uid();
  j   public.workshop_jobs;
  c   public.gear_catalog;
  back int;
  mid boolean;
begin
  if uid is null then raise exception 'gear:not_signed_in' using errcode = '28000'; end if;
  perform pg_advisory_xact_lock(hashtext('gear:' || uid::text));
  perform public.workshop_settle(uid);
  select * into j from public.workshop_jobs where id = p_job and user_id = uid for update;
  if not found then raise exception 'gear:no_job' using errcode = '22023'; end if;
  if j.state <> 'queued' then raise exception 'gear:job_done' using errcode = '22023'; end if;
  select * into c from public.gear_catalog where id = j.item_id;
  -- the next tier can't stay queued on top of a tier that's gone
  if c.kind = 'gear' and exists (
    select 1 from public.workshop_jobs x join public.gear_catalog n on n.id = x.item_id
    where x.user_id = uid and x.state = 'queued' and n.kind = 'gear' and n.sport = c.sport and n.slot = c.slot and n.tier > c.tier
  ) then
    raise exception 'gear:has_next' using errcode = '22023';
  end if;
  mid := j.started_at <= now();
  -- cancelRefund()
  back := case
    when not mid then j.cost
    when exists (select 1 from public.workshop_jobs x where x.user_id = uid and x.state = 'cancelled' and x.midfit) then
      floor(j.cost * (public.workshop_rules() ->> 'cancelRefundBp')::int / 10000.0)::int
    else j.cost
  end;
  update public.workshop_jobs set state = 'cancelled', cancelled_at = now(), midfit = mid, refund = back where id = j.id;
  update public.coin_spends set coins = greatest(0, coins - back) where id = j.spend_id;
  perform public.workshop_reflow(uid, j.bay);
  return public.wallet_for(uid);
end;
$$;

create or replace function public.workshop_skip(p_job bigint, p_kind text default 'gel')
returns json language plpgsql security definer set search_path = public as $$
declare
  uid uuid := auth.uid();
  j   public.workshop_jobs;
begin
  if uid is null then raise exception 'gear:not_signed_in' using errcode = '28000'; end if;
  perform pg_advisory_xact_lock(hashtext('gear:' || uid::text));
  perform public.workshop_settle(uid);
  if not (public.workshop_rules() -> 'skipKinds') ? p_kind then raise exception 'gear:unknown_item' using errcode = '22023'; end if;
  select * into j from public.workshop_jobs where id = p_job and user_id = uid for update;
  if not found then raise exception 'gear:no_job' using errcode = '22023'; end if;
  if j.state <> 'queued' then raise exception 'gear:job_done' using errcode = '22023'; end if;
  if j.started_at > now() then raise exception 'gear:not_fitting' using errcode = '22023'; end if;
  if public.fuel_held(uid, p_kind) < 1 then raise exception 'gear:fuel_none' using errcode = '22023'; end if;
  update public.workshop_jobs set finishes_at = greatest(started_at, now()), skipped_with = p_kind where id = j.id;
  perform public.workshop_settle(uid);
  perform public.workshop_reflow(uid, j.bay);
  return public.wallet_for(uid);
end;
$$;

-- ---- what the app reads -----------------------------------------------------------------

-- settles, then: the bays, every job not cancelled long ago, and the server's now
create or replace function public.workshop()
returns json language plpgsql security definer set search_path = public as $$
declare uid uuid := auth.uid();
begin
  if uid is null then raise exception 'gear:not_signed_in' using errcode = '28000'; end if;
  perform public.workshop_settle(uid);
  return json_build_object(
    'now', now(),
    'bays', public.workshop_bays(uid),
    'jobs', coalesce((select json_agg(json_build_object('id', j.id, 'item_id', j.item_id, 'cost', j.cost, 'bay', j.bay,
              'queued_at', j.queued_at, 'started_at', j.started_at, 'finishes_at', j.finishes_at, 'state', j.state,
              'skipped_with', j.skipped_with, 'midfit', j.midfit, 'refund', j.refund) order by j.started_at, j.id)
            from public.workshop_jobs j
            where j.user_id = uid and (j.state = 'queued' or j.finishes_at > now() - interval '7 days' or j.skipped_with is not null
              or (j.state = 'cancelled' and j.midfit))), '[]'::json));
end;
$$;

-- ---- fuel counts now include gels spent in the workshop -----------------------------------

create or replace function public.wallet_for(p_user uuid)
returns json language sql stable set search_path = public as $$
  with f as (select * from public.wallet_fold(p_user)),
  k as (select key as kind from jsonb_each(public.gear_rules() -> 'fuel' -> 'items')),
  held as (select json_object_agg(k.kind, public.fuel_held(p_user, k.kind)) as j from k),
  a as (
    select kind, started_at, expires_at, until_next from public.user_boosts
    where user_id = p_user and started_at <= now() and now() < expires_at
    order by started_at desc limit 1
  )
  select json_build_object(
    'coins', f.coins, 'carbs', f.carbs, 'cap', (public.gear_rules() ->> 'storageCap')::bigint,
    'earned', json_build_object('coins', f.earned_coins, 'carbs', f.earned_carbs),
    'spent', json_build_object('coins', f.spent_coins, 'carbs', f.spent_carbs),
    'lost', json_build_object('coins', f.lost_coins, 'carbs', f.lost_carbs),
    'held', held.j,
    'active', (select json_build_object('kind', a.kind, 'started_at', a.started_at, 'expires_at', a.expires_at, 'until_next', a.until_next) from a))
  from f, held;
$$;

create or replace function public.use_gel(p_kind text default 'gel')
returns json language plpgsql security definer set search_path = public as $$
declare
  uid  uuid := auth.uid();
  fr   jsonb := public.gear_rules() -> 'fuel';
  it   jsonb := public.gear_rules() -> 'fuel' -> 'items' -> p_kind;
begin
  if uid is null then raise exception 'gear:not_signed_in' using errcode = '28000'; end if;
  if it is null then raise exception 'gear:unknown_item' using errcode = '22023'; end if;
  perform pg_advisory_xact_lock(hashtext('gear:' || uid::text));
  if exists (select 1 from public.user_boosts where user_id = uid and started_at <= now() and now() < expires_at) then
    raise exception 'gear:fuel_active' using errcode = '22023';
  end if;
  if (select count(*) from public.user_boosts
      where user_id = uid and kind = p_kind
        and started_at > now() - make_interval(days => (fr ->> 'windowDays')::int)) >= (it ->> 'perWindow')::int then
    raise exception 'gear:fuel_limit' using errcode = '22023';
  end if;
  if public.fuel_held(uid, p_kind) < 1 then raise exception 'gear:fuel_none' using errcode = '22023'; end if;
  if coalesce((it ->> 'nextWorkout')::boolean, false) then
    insert into public.user_boosts (user_id, kind, started_at, expires_at, multiplier, until_next)
    values (uid, p_kind, now(), 'infinity', 1 + (it ->> 'boostBp')::numeric / 10000, true);
  else
    insert into public.user_boosts (user_id, kind, started_at, expires_at, multiplier)
    values (uid, p_kind, now(), now() + make_interval(hours => (it ->> 'hours')::int), 1 + (it ->> 'boostBp')::numeric / 10000);
  end if;
  return public.wallet_for(uid);
end;
$$;

