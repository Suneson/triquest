-- ---- what a session measured ----------------------------------------------------------

-- a json number as float8, or null (Number() in rewards.js: '' and junk are null)
create or replace function public.chest_num(p text)
returns float8 language sql immutable set search_path = public as $$
  select case when p ~ '^\s*-?(\d+\.?\d*|\.\d+)([eE][-+]?\d+)?\s*$' then p::float8 end;
$$;

-- sessionMinutes(): Strava's moving time, else the logged minutes
create or replace function public.chest_minutes(w public.workouts)
returns float8 language sql immutable set search_path = public as $$
  select coalesce(public.chest_num(w.actual ->> 'movingSec') / 60, greatest(0, coalesce(w.duration_min, 0))::float8);
$$;

-- sessionKm(): Strava's distance, else the logged distance
create or replace function public.chest_km(w public.workouts)
returns float8 language sql immutable set search_path = public as $$
  select greatest(0, coalesce(public.chest_num(w.actual ->> 'distanceKm'), w.distance_km::float8, 0));
$$;

-- workoutDifficulty(): 'easy' | 'moderate' | 'hard' | 'brutal'
create or replace function public.chest_difficulty(w public.workouts)
returns text language plpgsql immutable set search_path = public as $$
declare
  r    jsonb := public.chest_rules();
  m    float8 := public.chest_minutes(w);
  km   float8 := public.chest_km(w);
  mile float8 := (r -> 'milestoneKm' ->> w.type)::float8;
  i    int;
begin
  if w.type = 'mobility' then return 'easy'; end if;
  if (mile is not null and km >= mile) or (w.type = 'brick' and m >= (r ->> 'brickMinutes')::float8) then return 'brutal'; end if;
  i := case when m < (r -> 'minutes' ->> 0)::float8 then 0
            when m < (r -> 'minutes' ->> 1)::float8 then 1
            when m < (r -> 'minutes' ->> 2)::float8 then 2 else 3 end;
  if w.intensity = 'race' then
    i := greatest(i, case when m >= (r ->> 'raceMinutes')::float8 then 3 else 2 end);
  elsif (r -> 'hardLabels') ? coalesce(w.intensity, '') then
    i := greatest(i, least(2, i + 1));
  end if;
  return (r -> 'difficulties' ->> i);
end;
$$;

-- ---- the roll and the bonus -----------------------------------------------------------

-- rollChestTier(): the tier for a number in [0, 1), against chestOdds() (switched-off
-- tiers pass their share to the enabled tier below). Same float8 sums, same order, as JS.
create or replace function public.chest_roll(p_difficulty text, p_r float8)
returns text language plpgsql immutable set search_path = public as $$
declare
  r     jsonb := public.chest_rules();
  tiers text[] := array(select jsonb_array_elements_text(r -> 'tiers'));
  odds  jsonb := coalesce(r -> 'odds' -> p_difficulty, r -> 'odds' -> 'easy');
  share float8[] := array_fill(null::float8, array[array_length(tiers, 1)]);
  total float8 := 0;
  carry float8 := 0;
  p     float8;
  x     float8;
  acc   float8 := 0;
  last  text := 'common';
  i     int;
begin
  for i in 1 .. array_length(tiers, 1) loop total := total + (odds ->> tiers[i])::float8; end loop;
  for i in reverse array_length(tiers, 1) .. 1 loop
    p := (odds ->> tiers[i])::float8 + carry;
    if (r -> 'enabled' ->> tiers[i])::boolean then share[i] := (p / total) * 100; carry := 0; else carry := p; end if;
  end loop;
  if carry <> 0 then share[1] := coalesce(share[1], 0) + (carry / total) * 100; end if;
  x := least(greatest(coalesce(p_r, 0), 0), 0.999999999) * 100;
  for i in 1 .. array_length(tiers, 1) loop
    continue when share[i] is null;
    acc := acc + share[i];
    last := tiers[i];
    if x < acc then return tiers[i]; end if;
  end loop;
  return last;
end;
$$;

-- chestBonus(): the tier's flat coins and carbs plus its share of the session's own
create or replace function public.chest_bonus(p_tier text, p_xp numeric, out coins int, out carbs int)
language sql immutable set search_path = public as $$
  select (b ->> 'coins')::int + floor(floor(greatest(coalesce(p_xp, 0), 0) * (g ->> 'coinsPerXp')::numeric) * (b ->> 'pct')::numeric / 100)::int,
         (b ->> 'carbs')::int + floor(floor(greatest(coalesce(p_xp, 0), 0) * (g ->> 'carbsPerXp')::numeric) * (b ->> 'pct')::numeric / 100)::int
  from (select coalesce(public.chest_rules() -> 'bonus' -> p_tier, public.chest_rules() -> 'bonus' -> 'common') as b, public.gear_rules() as g) x;
$$;

-- ---- the chests ---------------------------------------------------------------------------

create table if not exists public.reward_chests (
  id                 bigserial primary key,
  user_id            uuid not null references auth.users (id) on delete cascade,
  source             text not null check (source in ('workout', 'gift')),
  workout_id         text,
  strava_activity_id bigint,
  day                date not null,
  difficulty         text check (difficulty in ('easy', 'moderate', 'hard', 'brutal')),
  tier               text not null check (tier in ('common', 'uncommon', 'rare', 'epic', 'legendary', 'mythic')),
  xp                 numeric not null default 0,
  coins              int not null check (coins >= 0),
  carbs              int not null check (carbs >= 0),
  created_at         timestamptz not null default now(),
  opened_at          timestamptz
);
create unique index if not exists reward_chests_workout on public.reward_chests (user_id, workout_id) where workout_id is not null;
create unique index if not exists reward_chests_strava on public.reward_chests (user_id, strava_activity_id) where strava_activity_id is not null;
create index if not exists reward_chests_user on public.reward_chests (user_id, created_at desc);
alter table public.reward_chests enable row level security;
do $$ begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'reward_chests' and policyname = 'reward_chests_own') then
    create policy reward_chests_own on public.reward_chests for select using (user_id = auth.uid());
  end if;
end $$;
grant select on public.reward_chests to authenticated;

-- chestSessions(): make the chests a user's sessions have earned and don't have yet,
-- in ledger order, at most perDay a day. Callers hold the user's gear lock.
create or replace function public.chests_grant(p_user uuid)
returns int language plpgsql volatile security definer set search_path = public as $$
declare
  r     jsonb := public.chest_rules();
  e     record;
  made  int;
  tier  text;
  b     record;
  n     int := 0;
begin
  -- only ever for yourself (my_chests() is the way in)
  if auth.uid() is distinct from p_user then
    raise exception 'gear:not_yours' using errcode = '42501';
  end if;
  for e in
    select l.id, l.date, l.xp, w.strava_activity_id, public.chest_difficulty(w) as d
    from public.xp_ledger(p_user) l
    join public.workouts w on w.id = l.id and w.user_id = p_user
    where l.date >= (r ->> 'since')::date and l.xp > 0
      and public.chest_minutes(w) >= (r ->> 'minMinutes')::float8
      and not exists (select 1 from public.reward_chests c where c.user_id = p_user
                      and (c.workout_id = l.id or (w.strava_activity_id is not null and c.strava_activity_id = w.strava_activity_id)))
    order by l.date,
             coalesce(w.completed_at, case when w.extra ->> 'gymLoggedAt' ~ '^\d{4}-\d{2}-\d{2}T' then (w.extra ->> 'gymLoggedAt')::timestamptz end) nulls first,
             l.id
  loop
    select count(*) into made from public.reward_chests c where c.user_id = p_user and c.source = 'workout' and c.day = e.date;
    continue when made >= (r ->> 'perDay')::int;
    tier := public.chest_roll(e.d, random());
    select * into b from public.chest_bonus(tier, e.xp);
    insert into public.reward_chests (user_id, source, workout_id, strava_activity_id, day, difficulty, tier, xp, coins, carbs)
    values (p_user, 'workout', e.id, e.strava_activity_id, e.date, e.d, tier, e.xp, b.coins, b.carbs);
    n := n + 1;
  end loop;
  return n;
end;
$$;

-- a chest as the app reads it
create or replace function public.chest_json(c public.reward_chests)
returns json language sql stable set search_path = public as $$
  select json_build_object('id', c.id, 'source', c.source, 'workout_id', c.workout_id, 'day', to_char(c.day, 'YYYY-MM-DD'),
    'difficulty', c.difficulty, 'tier', c.tier, 'xp', c.xp, 'coins', c.coins, 'carbs', c.carbs,
    'created_at', c.created_at, 'opened_at', c.opened_at);
$$;

-- The app's chests: makes any that are due, then lists the unopened ones and the
-- last month's opened ones, newest first. { admin, chests: [...] }
create or replace function public.my_chests()
returns json language plpgsql volatile security definer set search_path = public as $$
declare
  uid uuid := auth.uid();
begin
  if uid is null then raise exception 'gear:not_signed_in' using errcode = '28000'; end if;
  perform pg_advisory_xact_lock(hashtext('gear:' || uid::text));
  perform public.chests_grant(uid);
  return json_build_object(
    'admin', public.is_app_admin(uid),
    'chests', coalesce((
      select json_agg(public.chest_json(c) order by c.created_at desc, c.id desc)
      from (select * from public.reward_chests
            where user_id = uid and (opened_at is null or opened_at > now() - interval '30 days')
            order by created_at desc, id desc limit 60) c
    ), '[]'::json));
end;
$$;

-- Open a chest: from now on the wallet counts its bonus. Opening twice is harmless.
create or replace function public.open_chest(p_id bigint)
returns json language plpgsql volatile security definer set search_path = public as $$
declare
  uid uuid := auth.uid();
  c   public.reward_chests;
begin
  if uid is null then raise exception 'gear:not_signed_in' using errcode = '28000'; end if;
  perform pg_advisory_xact_lock(hashtext('gear:' || uid::text));
  update public.reward_chests set opened_at = now()
  where id = p_id and user_id = uid and opened_at is null
  returning * into c;
  if found then return json_build_object('already', false, 'chest', public.chest_json(c)); end if;
  select * into c from public.reward_chests where id = p_id and user_id = uid;
  if not found then raise exception 'gear:chest_unknown' using errcode = '22023'; end if;
  return json_build_object('already', true, 'chest', public.chest_json(c));
end;
$$;

-- Admins only: a chest of any switched-on tier, for yourself (to try the animations).
create or replace function public.admin_gift_chest(p_tier text)
returns json language plpgsql volatile security definer set search_path = public as $$
declare
  uid uuid := auth.uid();
  b   record;
  c   public.reward_chests;
begin
  if uid is null then raise exception 'gear:not_signed_in' using errcode = '28000'; end if;
  if not public.is_app_admin(uid) then raise exception 'gear:not_admin' using errcode = '42501'; end if;
  if coalesce((public.chest_rules() -> 'enabled' ->> p_tier)::boolean, false) is not true then
    raise exception 'gear:chest_tier' using errcode = '22023';
  end if;
  select * into b from public.chest_bonus(p_tier, 0);
  insert into public.reward_chests (user_id, source, day, tier, coins, carbs)
  values (uid, 'gift', (now() at time zone 'utc')::date, p_tier, b.coins, b.carbs)
  returning * into c;
  return public.chest_json(c);
end;
$$;

-- ---- the wallet: opened chests are rank 6 ---------------------------------------------------

create or replace function public.wallet_fold(p_user uuid)
returns table (coins bigint, carbs bigint, earned_coins bigint, earned_carbs bigint,
               spent_coins bigint, spent_carbs bigint, lost_coins bigint, lost_carbs bigint)
language plpgsql stable set search_path = public as $$
declare
  r     jsonb := public.gear_rules();
  cap   bigint := (r ->> 'storageCap')::bigint;
  since date := (r ->> 'since')::date;
  e     record;
  room  bigint;
begin
  earned_coins := (r ->> 'starterPurse')::bigint;  earned_carbs := (r ->> 'starterCarbs')::bigint;
  coins := least(cap, earned_coins);               carbs := least(cap, earned_carbs);
  spent_coins := 0; spent_carbs := 0; lost_coins := 0; lost_carbs := 0;
  for e in
    with days as (
      select l.date, sum(l.xp) as x from public.xp_ledger(p_user) l where l.date >= since group by l.date
    ), ev as (
      select to_char(d.date, 'YYYY-MM-DD') || 'T00:00:00.000Z' as at, 0 as rank, to_char(d.date, 'YYYY-MM-DD') as key,
             least((r ->> 'dailyCoinCap')::numeric, floor(greatest(d.x, 0) * (r ->> 'coinsPerXp')::numeric))::bigint as c,
             least((r ->> 'dailyCarbCap')::numeric, floor(greatest(d.x, 0) * (r ->> 'carbsPerXp')::numeric))::bigint as g
      from days d
      union all
      select to_char(q.day, 'YYYY-MM-DD') || 'T00:00:00.000Z', 1, q.quest_id,
             (public.quest_reward(q.quest_id) ->> 'coins')::bigint, (public.quest_reward(q.quest_id) ->> 'carbs')::bigint
      from public.quest_completions q
      where q.user_id = p_user and q.day >= since and public.quest_reward(q.quest_id) is not null
      union all
      select to_char(s.created_at at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'), 2, lpad(s.id::text, 12, '0'),
             case when s.currency = 'coins' then -s.coins else 0 end,
             case when s.currency = 'carbs' then -s.coins else 0 end
      from public.coin_spends s where s.user_id = p_user
      union all
      select to_char(m.created_at at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'), 3, lpad(m.id::text, 12, '0'),
             m.coins::bigint, 0
      from public.coin_moves m where m.user_id = p_user
      union all
      select to_char(a.at at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'), 4, a.sport || ':' || a.tier,
             a.coins::bigint, 0
      from public.collection_awards(p_user) a
      union all
      select to_char(m.claimed_at at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'), 5,
             to_char(m.week, 'YYYY-MM-DD') || ':' || m.mission_id, m.coins::bigint, m.carbs::bigint
      from public.mission_claims m where m.user_id = p_user
      union all
      select to_char(c.opened_at at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'), 6,
             lpad(c.id::text, 12, '0'), c.coins::bigint, c.carbs::bigint
      from public.reward_chests c where c.user_id = p_user and c.opened_at is not null
    )
    select * from ev order by at collate "C", rank, key collate "C"
  loop
    if e.c > 0 then
      room := greatest(0, cap - coins);
      coins := coins + least(e.c, room); earned_coins := earned_coins + e.c; lost_coins := lost_coins + greatest(0, e.c - room);
    elsif e.c < 0 then
      coins := coins + e.c; spent_coins := spent_coins - e.c;
    end if;
    if e.g > 0 then
      room := greatest(0, cap - carbs);
      carbs := carbs + least(e.g, room); earned_carbs := earned_carbs + e.g; lost_carbs := lost_carbs + greatest(0, e.g - room);
    elsif e.g < 0 then
      carbs := carbs + e.g; spent_carbs := spent_carbs - e.g;
    end if;
  end loop;
  return next;
end;
$$;

