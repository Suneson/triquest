-- The rate limit (0012) also guards cards: a row that carries a challenge or a
-- trophy can only come from post_card() below, never from a client insert.
create or replace function public.room_rate_limit()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if (new.challenge_id is not null or new.feat_id is not null)
     and coalesce(current_setting('moske.room_card', true), '') <> 'on' then
    raise exception 'cards are posted by the server' using errcode = '42501';
  end if;
  if (select count(*) from public.room_messages
       where user_id = new.user_id and created_at > now() - interval '1 minute') >= 10 then
    raise exception 'Slow down: at most 10 messages a minute' using errcode = 'P0001';
  end if;
  new.created_at := now(); -- the server's clock, not the client's
  return new;
end;
$$;

create or replace function public.post_card(p_user uuid, p_body text, p_challenge uuid, p_feat text)
returns void language plpgsql security definer set search_path = public as $$
begin
  perform set_config('moske.room_card', 'on', true);
  insert into public.room_messages (user_id, body, challenge_id, feat_id) values (p_user, left(p_body, 500), p_challenge, p_feat);
  perform set_config('moske.room_card', 'off', true);
end;
$$;

-- ---- creating, joining, leaving, cancelling ----------------------------------------------------

create or replace function public.challenge_join_now(c public.challenges, p_user uuid)
returns void language plpgsql security definer set search_path = public as $$
declare
  why text;
  others uuid[];
begin
  if (select count(*) from public.challenge_participants where challenge_id = c.id and status = 'joined')
     >= (public.challenge_rules() ->> 'maxParticipants')::int then
    raise exception 'ch:full' using errcode = '22023';
  end if;
  select array_agg(user_id) into others from public.challenge_participants where challenge_id = c.id and status = 'joined';
  why := public.stake_block(p_user, c.stake, others);
  if why is not null then raise exception 'ch:%', why using errcode = '22023'; end if;
  insert into public.challenge_participants (challenge_id, user_id, status, stake, joined_at)
  values (c.id, p_user, 'joined', c.stake, now())
  on conflict (challenge_id, user_id) do update set status = 'joined', stake = excluded.stake, joined_at = excluded.joined_at;
  if c.stake > 0 then
    insert into public.coin_moves (user_id, challenge_id, kind, coins) values (p_user, c.id, 'stake', -c.stake);
  end if;
end;
$$;

-- checkChallenge() + the creator joins (and stakes) at once; a room challenge posts its card
create or replace function public.create_challenge(p jsonb)
returns uuid language plpgsql security definer set search_path = public as $$
declare
  uid uuid := auth.uid();
  cr jsonb := public.challenge_rules();
  c public.challenges;
  inv uuid;
  invitees uuid[];
  days int;
begin
  if uid is null then raise exception 'ch:not_signed_in' using errcode = '28000'; end if;
  perform pg_advisory_xact_lock(hashtext('gear:' || uid::text));
  c.id := gen_random_uuid(); c.creator := uid;
  c.kind := p ->> 'kind'; c.sport := p ->> 'sport';
  c.params := coalesce(p -> 'params', '{}'::jsonb);
  c.starts_on := (p ->> 'starts_on')::date; c.ends_on := (p ->> 'ends_on')::date;
  c.stake := coalesce((p ->> 'stake')::int, 0); c.payout := coalesce(p ->> 'payout', 'winner');
  c.visibility := coalesce(p ->> 'visibility', 'room'); c.state := 'open'; c.created_at := now();
  select array_agg(distinct (x)::uuid) into invitees from jsonb_array_elements_text(coalesce(p -> 'invitees', '[]'::jsonb)) x;
  -- what a challenge may be
  if not (cr -> 'kinds') ? c.kind then raise exception 'ch:kind' using errcode = '22023'; end if;
  if not (cr -> 'kinds' -> c.kind) ? c.sport then raise exception 'ch:sport' using errcode = '22023'; end if;
  days := c.ends_on - c.starts_on + 1;
  if days < (cr ->> 'minWindowDays')::int or days > (cr ->> 'maxWindowDays')::int then raise exception 'ch:window' using errcode = '22023'; end if;
  if c.starts_on <= current_date or c.starts_on > current_date + (cr ->> 'maxStartAheadDays')::int then
    raise exception 'ch:start' using errcode = '22023';
  end if;
  if c.stake > (cr ->> 'maxStake')::int then raise exception 'ch:stake' using errcode = '22023'; end if;
  if not (cr -> 'payouts') ? c.payout then raise exception 'ch:payout' using errcode = '22023'; end if;
  if c.kind = 'fastest' and (cr -> 'fastest' -> c.sport -> (c.params ->> 'dist')) is null then raise exception 'ch:dist' using errcode = '22023'; end if;
  if c.kind = 'longest' and not (coalesce((c.params ->> 'targetMin')::int, 0) between 10 and (cr -> 'longestMaxMin' ->> c.sport)::int) then
    raise exception 'ch:target' using errcode = '22023';
  end if;
  if c.kind = 'segment' and not coalesce((c.params ->> 'segmentId')::bigint, 0) > 0 then raise exception 'ch:segment' using errcode = '22023'; end if;
  if c.visibility = 'direct' then
    invitees := array_remove(invitees, uid);
    if coalesce(array_length(invitees, 1), 0) < 1 or array_length(invitees, 1) > (cr ->> 'maxParticipants')::int - 1 then
      raise exception 'ch:invitees' using errcode = '22023';
    end if;
    foreach inv in array invitees loop
      -- declining is free, and direct challenges can be switched off altogether
      if coalesce((select settings ->> 'directChallenges' from public.profiles where id = inv), 'true') = 'false' then
        raise exception 'ch:no_direct' using errcode = '22023';
      end if;
    end loop;
  end if;
  if (select count(*) from public.challenges where creator = uid and state = 'open') >= (cr ->> 'maxOpenCreated')::int then
    raise exception 'ch:open_max' using errcode = '22023';
  end if;
  if c.visibility = 'room' then
    if (select count(*) from public.room_messages where user_id = uid and challenge_id is not null and created_at > now() - interval '1 day')
       >= (cr ->> 'roomCardsPerDay')::int then
      raise exception 'ch:room_day' using errcode = '22023';
    end if;
    if (select count(*) from public.challenges where visibility = 'room' and state = 'open' and ends_on >= current_date)
       >= (cr ->> 'roomOpenMax')::int then
      raise exception 'ch:room_full' using errcode = '22023';
    end if;
  end if;
  insert into public.challenges select c.*;
  perform public.challenge_join_now(c, uid);
  if c.visibility = 'direct' then
    insert into public.challenge_participants (challenge_id, user_id, status)
    select c.id, x, 'invited' from unnest(invitees) x;
  else
    perform public.post_card(uid, 'challenge', c.id, null);
  end if;
  return c.id;
end;
$$;

create or replace function public.join_challenge(p_id uuid)
returns void language plpgsql security definer set search_path = public as $$
declare
  uid uuid := auth.uid();
  c public.challenges;
begin
  if uid is null then raise exception 'ch:not_signed_in' using errcode = '28000'; end if;
  perform pg_advisory_xact_lock(hashtext('gear:' || uid::text));
  select * into c from public.challenges where id = p_id for update;
  if not found or not public.challenge_visible(p_id, uid) then raise exception 'ch:not_found' using errcode = '22023'; end if;
  if c.state <> 'open' or current_date >= c.starts_on then raise exception 'ch:closed' using errcode = '22023'; end if;
  if exists (select 1 from public.challenge_participants where challenge_id = p_id and user_id = uid and status = 'joined') then
    raise exception 'ch:joined' using errcode = '22023';
  end if;
  if c.visibility = 'direct' and not exists (select 1 from public.challenge_participants where challenge_id = p_id and user_id = uid) then
    raise exception 'ch:not_invited' using errcode = '22023';
  end if;
  perform public.challenge_join_now(c, uid);
end;
$$;

-- decline an invitation, or leave before the start (a stake comes back in full)
create or replace function public.decline_challenge(p_id uuid)
returns void language plpgsql security definer set search_path = public as $$
declare
  uid uuid := auth.uid();
  c public.challenges;
  p public.challenge_participants;
begin
  if uid is null then raise exception 'ch:not_signed_in' using errcode = '28000'; end if;
  select * into c from public.challenges where id = p_id for update;
  if not found then raise exception 'ch:not_found' using errcode = '22023'; end if;
  if c.creator = uid then raise exception 'ch:creator' using errcode = '22023'; end if;
  if c.state <> 'open' or current_date >= c.starts_on then raise exception 'ch:closed' using errcode = '22023'; end if;
  select * into p from public.challenge_participants where challenge_id = p_id and user_id = uid for update;
  if not found or p.status = 'declined' then raise exception 'ch:not_invited' using errcode = '22023'; end if;
  if p.status = 'joined' and p.stake > 0 then
    insert into public.coin_moves (user_id, challenge_id, kind, coins) values (uid, p_id, 'refund', p.stake);
  end if;
  update public.challenge_participants set status = 'declined', stake = 0 where challenge_id = p_id and user_id = uid;
end;
$$;

-- refund every stake in full and close the challenge (the creator before the start, or too few joined)
create or replace function public.challenge_cancel_now(c public.challenges, p_reason text)
returns void language plpgsql security definer set search_path = public as $$
begin
  insert into public.coin_moves (user_id, challenge_id, kind, coins)
  select p.user_id, c.id, 'refund', p.stake from public.challenge_participants p
  where p.challenge_id = c.id and p.status = 'joined' and p.stake > 0;
  update public.challenges set state = 'cancelled', settled_at = now() where id = c.id;
  insert into public.challenge_results (challenge_id, outcome, rule, rows)
  values (c.id, 'cancelled', jsonb_build_object('reason', p_reason),
          coalesce((select jsonb_agg(jsonb_build_object('user', p.user_id, 'stake', p.stake, 'refund', p.stake))
                    from public.challenge_participants p where p.challenge_id = c.id and p.status = 'joined'), '[]'::jsonb))
  on conflict (challenge_id) do nothing;
end;
$$;

create or replace function public.cancel_challenge(p_id uuid)
returns void language plpgsql security definer set search_path = public as $$
declare
  uid uuid := auth.uid();
  c public.challenges;
begin
  select * into c from public.challenges where id = p_id for update;
  if not found or c.creator is distinct from uid then raise exception 'ch:not_yours' using errcode = '42501'; end if;
  if c.state <> 'open' or current_date >= c.starts_on then raise exception 'ch:closed' using errcode = '22023'; end if;
  perform public.challenge_cancel_now(c, 'creator');
end;
$$;

-- ---- settling (settle() in challenges.js) ---------------------------------------------------

-- one participant while settling
create type public.ch_score as (user_id uuid, stake int, score bigint, sessions text[], cut boolean, place bigint, payout int);

create or replace function public.resolve_challenge(p_id uuid)
returns text language plpgsql security definer set search_path = public as $$
declare
  cr jsonb := public.challenge_rules();
  c public.challenges;
  sc public.ch_score[];
  pot int; fee int; prize int; paid_out int;
  shares int[];
  q int;
  sum_paid int;
  g record;
  covered int;
  each_ int;
  joined int;
  pr record;
  fw record;
  lower_ boolean;
begin
  select * into c from public.challenges where id = p_id for update;
  if not found then raise exception 'ch:not_found' using errcode = '22023'; end if;
  if c.state <> 'open' then return c.state; end if;
  select count(*) into joined from public.challenge_participants where challenge_id = p_id and status = 'joined';
  -- started with fewer than two: cancelled, every stake back
  if current_date >= c.starts_on and joined < 2 then
    perform public.challenge_cancel_now(c, 'too_few');
    return 'cancelled';
  end if;
  if current_date < c.ends_on + (cr ->> 'graceDays')::int + 1 then return 'open'; end if;
  lower_ := (cr -> 'lowerWins') ? c.kind;

  -- every score, and its place (ties share it; no-shows have none)
  select array_agg(row(x.user_id, x.stake, x.score, x.sessions, x.cut, x.place, 0)::public.ch_score order by x.user_id)
    into sc
  from (
    select p.user_id, p.stake, s.score, s.sessions, s.cut,
           case when s.score is null then null
                when lower_ then rank() over (order by s.score asc nulls last)
                else rank() over (order by s.score desc nulls last) end as place
    from public.challenge_participants p, public.challenge_score(c, p.user_id) s
    where p.challenge_id = p_id and p.status = 'joined'
  ) x;

  select coalesce(sum(x.stake), 0), count(x.place) into pot, q from unnest(sc) x;
  if q = 0 then
    -- nobody had a session: void, every stake back, nothing burned
    select array_agg(row(x.user_id, x.stake, x.score, x.sessions, x.cut, x.place, x.stake)::public.ch_score order by x.user_id)
      into sc from unnest(sc) x;
    fee := 0; prize := 0;
  else
    fee := floor(pot * (cr ->> 'feeBp')::int / 10000);
    prize := pot - fee;
    select array_agg(v::int order by o) into shares from jsonb_array_elements_text(cr -> 'payouts' -> c.payout) with ordinality as t(v, o);
    shares := shares[1:least(array_length(shares, 1), q)];
    select sum(v) into sum_paid from unnest(shares) v;
    for g in select x.place, count(*)::int as n from unnest(sc) x where x.place is not null group by x.place order by x.place loop
      select coalesce(sum(v), 0) into covered from unnest(shares[g.place:least(g.place + g.n - 1, array_length(shares, 1))]) v;
      if covered > 0 then
        each_ := floor(prize::numeric * covered / (sum_paid * g.n));
        select array_agg(row(x.user_id, x.stake, x.score, x.sessions, x.cut, x.place,
                             case when x.place = g.place then each_ else x.payout end)::public.ch_score order by x.user_id)
          into sc from unnest(sc) x;
      end if;
    end loop;
  end if;
  insert into public.coin_moves (user_id, challenge_id, kind, coins)
  select x.user_id, p_id, case when q = 0 then 'refund' else 'payout' end, x.payout from unnest(sc) x where x.payout > 0;
  select coalesce(sum(x.payout), 0) into paid_out from unnest(sc) x;
  insert into public.challenge_results (challenge_id, outcome, pot, fee, prize, burned, rule, rows)
  values (p_id, case when q = 0 then 'void' else 'settled' end, pot, fee, prize, pot - paid_out,
          jsonb_build_object('kind', c.kind, 'sport', c.sport, 'params', c.params, 'starts_on', c.starts_on, 'ends_on', c.ends_on,
                             'payout', c.payout, 'stake', c.stake, 'feeBp', (cr ->> 'feeBp')::int,
                             'shares', cr -> 'payouts' -> c.payout, 'lowerWins', lower_),
          coalesce((select jsonb_agg(jsonb_build_object('user', x.user_id, 'stake', x.stake, 'score', x.score, 'place', x.place,
                      'payout', x.payout, 'sessions', x.sessions, 'cut', x.cut) order by x.place nulls last, x.user_id)
                    from unnest(sc) x), '[]'::jsonb));
  update public.challenges set state = 'settled', settled_at = now() where id = p_id;

  -- a room challenge that produced a feat posts the trophy under it (feats are
  -- awarded at every Strava sync, days before a challenge settles)
  if c.visibility = 'room' then
    for pr in select x.user_id, x.sessions from unnest(sc) x where coalesce(array_length(x.sessions, 1), 0) > 0 loop
      for fw in select uf.feat_id from public.user_feats uf
                where uf.user_id = pr.user_id and uf.workout_id = any(pr.sessions) loop
        perform public.post_card(pr.user_id, 'trophy', p_id, fw.feat_id);
      end loop;
    end loop;
  end if;
  return 'settled';
end;
$$;

-- every challenge that's due: started with too few, or past its grace. Idempotent;
-- runs on a schedule and whenever someone opens the challenges.
create or replace function public.resolve_due()
returns int language plpgsql security definer set search_path = public as $$
declare
  c record;
  n int := 0;
begin
  for c in
    select ch.id from public.challenges ch
    where ch.state = 'open'
      and (ch.ends_on + (public.challenge_rules() ->> 'graceDays')::int + 1 <= current_date
           or (ch.starts_on <= current_date
               and (select count(*) from public.challenge_participants p where p.challenge_id = ch.id and p.status = 'joined') < 2))
    order by ch.ends_on limit 50
  loop
    perform public.resolve_challenge(c.id);
    n := n + 1;
  end loop;
  return n;
end;
$$;

-- ---- the admin view: pairs whose coins only ever flow one way (no automatic punishment) --------

create or replace function public.admin_pair_flags()
returns table (a uuid, b uuid, a_name text, b_name text, together int, one_on_one int,
               a_wins int, b_wins int, net_a_to_b bigint, a_no_shows int, b_no_shows int, flagged boolean)
language sql stable security definer set search_path = public as $$
  with s as (
    select c.id, c.created_at, (r.rows) as rows, jsonb_array_length(r.rows) as size
    from public.challenges c join public.challenge_results r on r.challenge_id = c.id
    where c.stake > 0 and r.outcome = 'settled' and c.created_at > now() - interval '90 days'
  ), pr as (
    select s.id, s.size,
           (x ->> 'user')::uuid as u1, (y ->> 'user')::uuid as u2,
           (x ->> 'payout')::int - (x ->> 'stake')::int as net1,
           (x ->> 'place') is null as ns1, (y ->> 'place') is null as ns2,
           coalesce((x ->> 'place')::int, 99) < coalesce((y ->> 'place')::int, 99) as w1,
           coalesce((y ->> 'place')::int, 99) < coalesce((x ->> 'place')::int, 99) as w2
    from s, jsonb_array_elements(s.rows) x, jsonb_array_elements(s.rows) y
    where (x ->> 'user') < (y ->> 'user')
  ), agg as (
    select u1 as a, u2 as b, count(*)::int as together, count(*) filter (where size = 2)::int as one_on_one,
           count(*) filter (where w1)::int as a_wins, count(*) filter (where w2)::int as b_wins,
           -sum(net1)::bigint as net_a_to_b,
           count(*) filter (where ns1)::int as a_no_shows, count(*) filter (where ns2)::int as b_no_shows
    from pr group by u1, u2
  )
  select g.a, g.b, pa.display_name, pb.display_name, g.together, g.one_on_one, g.a_wins, g.b_wins, g.net_a_to_b,
         g.a_no_shows, g.b_no_shows,
         (g.one_on_one >= 4 and greatest(g.a_wins, g.b_wins) * 10 >= g.one_on_one * 8)
           or abs(g.net_a_to_b) >= 300 or greatest(g.a_no_shows, g.b_no_shows) >= 2
  from agg g left join public.profiles pa on pa.id = g.a left join public.profiles pb on pb.id = g.b
  where public.is_app_admin(auth.uid())
  order by 12 desc, abs(g.net_a_to_b) desc;
$$;

