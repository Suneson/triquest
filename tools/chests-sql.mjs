// chests-sql.mjs — writes the generated part of supabase/migrations/0027_reward_chests.sql
// (the chest rules: launch day, limits, odds, bonuses, the difficulty thresholds)
// from js/core/rewards.js, so the two can't drift. tests/rewards-sql.test.js
// fails if the file and this disagree.
//
//   node tools/chests-sql.mjs          rewrite the block in place
//   node tools/chests-sql.mjs --print  print it

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { CHEST_RULES, TIERS, DIFFICULTIES } from '../js/core/rewards.js';

export const MIGRATION = fileURLToPath(new URL('../supabase/migrations/0027_reward_chests.sql', import.meta.url));
export const BEGIN = '-- BEGIN GENERATED by tools/chests-sql.mjs from js/core/rewards.js — do not edit by hand';
export const END = '-- END GENERATED';

const lit = (v) => `'${String(v).replace(/'/g, "''")}'`;

export function generatedBlock() {
  const rules = JSON.stringify({ ...CHEST_RULES, tiers: TIERS, difficulties: DIFFICULTIES });
  return [
    BEGIN,
    'create or replace function public.chest_rules()',
    'returns jsonb language sql immutable set search_path = public as $$',
    `  select ${lit(rules)}::jsonb;`,
    '$$;',
    END,
  ].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  if (process.argv.includes('--print')) {
    console.log(generatedBlock());
  } else {
    const sql = readFileSync(MIGRATION, 'utf8');
    const a = sql.indexOf(BEGIN);
    const b = sql.indexOf(END, a);
    if (a < 0 || b < 0) throw new Error(`markers not found in ${MIGRATION}`);
    writeFileSync(MIGRATION, sql.slice(0, a) + generatedBlock() + sql.slice(b + END.length));
    console.log(`updated ${MIGRATION}`);
  }
}
