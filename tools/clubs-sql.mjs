// clubs-sql.mjs — writes the generated part of supabase/migrations/0026_clubs.sql
// (the club rules and the relay routes' distances) from js/core/clubs.js, so the
// two can't drift. tests/clubs-sql.test.js fails if the file and this disagree.
//
//   node tools/clubs-sql.mjs          rewrite the block in place
//   node tools/clubs-sql.mjs --print  print it

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { CLUB_RULES, RELAY_ROUTES } from '../js/core/clubs.js';

export const MIGRATION = fileURLToPath(new URL('../supabase/migrations/0026_clubs.sql', import.meta.url));
export const BEGIN = '-- BEGIN GENERATED by tools/clubs-sql.mjs from js/core/clubs.js — do not edit by hand';
export const END = '-- END GENERATED';

const lit = (v) => `'${String(v).replace(/'/g, "''")}'`;

export function generatedBlock() {
  const rules = JSON.stringify({ ...CLUB_RULES, routes: RELAY_ROUTES.map((r) => ({ id: r.id, km: r.km })) });
  return [
    BEGIN,
    'create or replace function public.club_rules()',
    'returns jsonb language sql immutable set search_path = public as $$',
    `  select ${lit(rules)}::jsonb;`,
    '$$;',
    END,
  ].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  if (process.argv.includes('--print')) {
    console.log(generatedBlock());
  } else {
    const sql = readFileSync(MIGRATION, 'utf8');
    const a = sql.indexOf(BEGIN);
    const b = sql.indexOf(END);
    if (a < 0 || b < 0) throw new Error('markers not found');
    writeFileSync(MIGRATION, sql.slice(0, a) + generatedBlock() + sql.slice(b + END.length));
    console.log(`wrote the generated block of ${MIGRATION}`);
  }
}
