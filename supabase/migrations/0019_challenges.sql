create table if not exists public.challenges (
  id         uuid primary key default gen_random_uuid(),
  creator    uuid not null references auth.users (id) on delete cascade,
  kind       text not null,
  sport      text not null,
  params     jsonb not null default '{}'::jsonb,
  starts_on  date not null,
  ends_on    date not null,
  stake      int not null default 0 check (stake >= 0),
  payout     text not null default 'winner',
  visibility text not null check (visibility in ('room', 'direct')),
  state      text not null default 'open' check (state in ('open', 'settled', 'cancelled')),
  created_at timestamptz not null default now(),
  settled_at timestamptz,
  check (ends_on >= starts_on)
