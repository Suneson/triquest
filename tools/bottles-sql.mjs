// bottles-sql.mjs — writes the generated part of supabase/migrations/0042_bottles.sql (bottle_rules(), with the
// bottles' order, which jsonb would lose) from js/core/bottles.js, so the two can't drift.
// tests/bottles-sql.test.js fails if the file and this disagree.
//
//   node tools/bottles-sql.mjs          rewrite the block in place
//   node tools/bottles-sql.mjs --print  print it

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { BOTTLE_RULES, BOTTLE_IDS } from '../js/core/bottles.js';

export const MIGRATION = fileURLToPath(new URL('../supabase/migrations/0042_bottles.sql', import.meta.url));
export const BEGIN = '-- BEGIN GENERATED by tools/bottles-sql.mjs from js/core/bottles.js — do not edit by hand';
export const END = '-- END GENERATED';

const lit = (v) => `'${String(v).replace(/'/g, "''")}'`;

export function generatedBlock() {
  return [
    BEGIN,
    'create or replace function public.bottle_rules()',
    'returns jsonb language sql immutable set search_path = public as $$',
    `  select ${lit(JSON.stringify({ ...BOTTLE_RULES, order: BOTTLE_IDS }))}::jsonb;`,
    '$$;',
    END,
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes('--print')) {
    console.log(generatedBlock());
  } else {
    const sql = readFileSync(MIGRATION, 'utf8');
    const a = sql.indexOf(BEGIN);
    const b = sql.indexOf(END, a);
    if (a < 0 || b < 0) throw new Error(`markers not found in ${MIGRATION}`);
    writeFileSync(MIGRATION, sql.slice(0, a) + generatedBlock() + sql.slice(b + END.length));
    console.log(`updated ${MIGRATION}`);
  }
}
