// gear-sql.mjs — writes the generated part of supabase/migrations/0014_gear.sql
// (the economy constants and the catalog) from js/core/gear.js, so the two
// can't drift. tests/gear-sql.test.js fails if the file and this disagree.
//
//   node tools/gear-sql.mjs          rewrite the block in place
//   node tools/gear-sql.mjs --print  print it

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { GEAR_RULES, GEAR_SINCE, catalogRows } from '../js/core/gear.js';

export const MIGRATION = fileURLToPath(new URL('../supabase/migrations/0014_gear.sql', import.meta.url));
export const BEGIN = '-- BEGIN GENERATED by tools/gear-sql.mjs from js/core/gear.js — do not edit by hand';
export const END = '-- END GENERATED';

const lit = (v) => (v == null ? 'null' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);

export function generatedBlock() {
  const rules = JSON.stringify({ ...GEAR_RULES, since: GEAR_SINCE });
  const rows = catalogRows().map((r) => `  (${[r.id, r.kind, r.sport, r.slot, r.tier, r.cost, r.boost_bp].map(lit).join(', ')})`);
  return [
    BEGIN,
    'create or replace function public.gear_rules()',
    'returns jsonb language sql immutable set search_path = public as $$',
    `  select ${lit(rules)}::jsonb;`,
    '$$;',
    '',
    'insert into public.gear_catalog (id, kind, sport, slot, tier, cost, boost_bp) values',
    rows.join(',\n'),
    'on conflict (id) do update set kind = excluded.kind, sport = excluded.sport, slot = excluded.slot,',
    '  tier = excluded.tier, cost = excluded.cost, boost_bp = excluded.boost_bp;',
    END,
  ].join('\n');
}

/** The migration text with its generated block replaced. */
export function withBlock(sql) {
  const a = sql.indexOf(BEGIN);
  const b = sql.indexOf(END);
  if (a < 0 || b < a) throw new Error('0014_gear.sql has no generated block markers');
  return sql.slice(0, a) + generatedBlock() + sql.slice(b + END.length);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes('--print')) console.log(generatedBlock());
  else {
    writeFileSync(MIGRATION, withBlock(readFileSync(MIGRATION, 'utf8')));
    console.log('wrote the generated block of', MIGRATION);
  }
}
