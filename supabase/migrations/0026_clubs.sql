create or replace function public.create_club(p_name text, p_crest text)
returns bigint language plpgsql security definer set search_path = public as $$
declare
  uid  uuid := auth.uid();
  r    jsonb := public.club_rules();
  nm   text := btrim(regexp_replace(coalesce(p_name, ''), '\s+', ' ', 'g'));
  cid  bigint;
begin
  if uid is null then raise exception 'club:not_signed_in' using errcode = '28000'; end if;
  perform pg_advisory_xact_lock(hashtext('club:' || uid::text));
  if public.club_of(uid) is not null then raise exception 'club:already_in' using errcode = '22023'; end if;
  if char_length(nm) < (r ->> 'nameMin')::int then raise exception 'club:name_short' using errcode = '22023'; end if;
  if char_length(nm) > (r ->> 'nameMax')::int then raise exception 'club:name_long' using errcode = '22023'; end if;
  if nm !~ '^[[:alnum:] .''&-]+$' then raise exception 'club:name_chars' using errcode = '22023'; end if;
  if not (r -> 'crests') ? p_crest then raise exception 'club:crest' using errcode = '22023'; end if;
  if exists (select 1 from public.clubs where lower(name) = lower(nm)) then raise exception 'club:name_taken' using errcode = '23505'; end if;
  insert into public.clubs (name, crest, created_by) values (nm, p_crest, uid) returning id into cid;
  insert into public.club_members (club_id, user_id, role) values (cid, uid, 'owner');
  insert into public.club_relays (club_id, route_id, started_by) values (cid, r -> 'routes' -> 0 ->> 'id', uid);
  return cid;
end;
$$;

create or replace function public.invite_to_club(p_username text)
returns json language plpgsql security definer set search_path = public as $$
declare
  uid  uuid := auth.uid();
  cid  bigint := public.club_of(auth.uid());
  who  uuid;
  c    public.clubs;
  me   text;
  iid  bigint;
begin
  if uid is null then raise exception 'club:not_signed_in' using errcode = '28000'; end if;
  if cid is null then raise exception 'club:not_member' using errcode = '42501'; end if;
  select id into who from public.profiles where lower(username) = lower(btrim(coalesce(p_username, ''), ' @'));
  if who is null then raise exception 'club:no_user' using errcode = '22023'; end if;
  if who = uid or public.club_has(cid, who) then raise exception 'club:already_member' using errcode = '22023'; end if;
  if (select count(*) from public.club_members where club_id = cid and left_at is null) >= (public.club_rules() ->> 'maxMembers')::int then
    raise exception 'club:full' using errcode = '22023';
  end if;
  -- an invitee who blocked the inviter never hears from them
  if exists (select 1 from public.user_blocks b where b.blocker = who and b.blocked = uid and b.unblocked_at is null) then
    return json_build_object('invited', true);
  end if;
  select * into c from public.clubs where id = cid;
  select coalesce(display_name, 'An athlete') into me from public.profiles where id = uid;
  insert into public.club_invites (club_id, user_id, invited_by) values (cid, who, uid)
  on conflict do nothing returning id into iid;
  if iid is not null then
    insert into public.notifications (user_id, kind, title, data)
    values (who, 'club_invite', me || ' invited you to ' || c.name,
            json_build_object('invite_id', iid, 'club_id', cid, 'club', c.name, 'from', me)::jsonb);
  end if;
  return json_build_object('invited', true);
end;
$$;

create or replace function public.respond_club_invite(p_invite bigint, p_accept boolean)
returns json language plpgsql security definer set search_path = public as $$
declare
  uid uuid := auth.uid();
  i   public.club_invites;
begin
  if uid is null then raise exception 'club:not_signed_in' using errcode = '28000'; end if;
  perform pg_advisory_xact_lock(hashtext('club:' || uid::text));
  select * into i from public.club_invites where id = p_invite and user_id = uid and responded_at is null;
  if not found then raise exception 'club:no_invite' using errcode = '22023'; end if;
  if p_accept then
    if public.club_of(uid) is not null then raise exception 'club:already_in' using errcode = '22023'; end if;
    perform pg_advisory_xact_lock(hashtext('club-size:' || i.club_id::text));
    if (select count(*) from public.club_members where club_id = i.club_id and left_at is null) >= (public.club_rules() ->> 'maxMembers')::int then
      raise exception 'club:full' using errcode = '22023';
    end if;
    insert into public.club_members (club_id, user_id, role) values (i.club_id, uid, 'member');
  end if;
  update public.club_invites set responded_at = now(), accepted = p_accept where id = i.id;
  update public.notifications set read_at = now()
   where user_id = uid and kind = 'club_invite' and (data ->> 'invite_id')::bigint = i.id and read_at is null;
  return json_build_object('club_id', case when p_accept then i.club_id end);
end;
$$;

-- leaving costs nothing; the longest-standing member takes the club on
create or replace function public.leave_club()
returns void language plpgsql security definer set search_path = public as $$
declare
  uid uuid := auth.uid();
  m   public.club_members;
begin
  if uid is null then raise exception 'club:not_signed_in' using errcode = '28000'; end if;
  select * into m from public.club_members where user_id = uid and left_at is null;
  if not found then return; end if;
  update public.club_members set left_at = now(), role = 'member' where id = m.id;
  if m.role = 'owner' then
    update public.club_members set role = 'owner'
     where id = (select id from public.club_members where club_id = m.club_id and left_at is null order by joined_at, id limit 1);
  end if;
end;
$$;

create or replace function public.set_club_target(p_hours int)
returns void language plpgsql security definer set search_path = public as $$
declare
  uid  uuid := auth.uid();
  cid  bigint := public.club_of(auth.uid());
  r    jsonb := public.club_rules();
  wk   date := (now() at time zone 'utc')::date - (extract(isodow from (now() at time zone 'utc')::date)::int - 1);
begin
  if uid is null then raise exception 'club:not_signed_in' using errcode = '28000'; end if;
  if cid is null then raise exception 'club:not_member' using errcode = '42501'; end if;
  if p_hours is null or p_hours < (r -> 'targetHours' ->> 'min')::int or p_hours > (r -> 'targetHours' ->> 'max')::int then
    raise exception 'club:target' using errcode = '22023';
  end if;
  insert into public.club_targets (club_id, week, minutes, set_by) values (cid, wk, p_hours * 60, uid)
  on conflict (club_id, week) do update set minutes = excluded.minutes, set_by = excluded.set_by, set_at = now();
end;
$$;

-- the next route, once the one being carried is finished
create or replace function public.start_relay()
returns json language plpgsql security definer set search_path = public as $$
declare
  uid   uuid := auth.uid();
  cid   bigint := public.club_of(auth.uid());
  r     jsonb := public.club_rules();
  cur   public.club_relays;
  idx   int;
  n     int := jsonb_array_length(public.club_rules() -> 'routes');
  next  text;
begin
  if uid is null then raise exception 'club:not_signed_in' using errcode = '28000'; end if;
  if cid is null then raise exception 'club:not_member' using errcode = '42501'; end if;
  perform pg_advisory_xact_lock(hashtext('club-relay:' || cid::text));
  select * into cur from public.club_relays where club_id = cid order by started_at desc, id desc limit 1;
  if found then
    select i - 1 into idx from jsonb_array_elements(r -> 'routes') with ordinality e(v, i) where e.v ->> 'id' = cur.route_id;
    if public.club_relay_km(cid, cur.started_at) < (r -> 'routes' -> coalesce(idx, 0) ->> 'km')::numeric then
      raise exception 'club:relay_running' using errcode = '22023';
    end if;
    next := r -> 'routes' -> ((coalesce(idx, -1) + 1) % n) ->> 'id';
  else
    next := r -> 'routes' -> 0 ->> 'id';
  end if;
  insert into public.club_relays (club_id, route_id, started_by) values (cid, next, uid);
  return json_build_object('route_id', next);
end;
$$;

