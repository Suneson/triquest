// collections-sql.mjs — writes the generated part of supabase/migrations/0023_collections.sql
// (the collection, blueprint and prestige rules) from js/core/collections.js and
// js/core/scenes.js, so the two can't drift. tests/collections-sql.test.js fails
// if the file and this disagree.
//
//   node tools/collections-sql.mjs          rewrite the block in place
//   node tools/collections-sql.mjs --print  print it

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { COLLECTION_RULES } from '../js/core/collections.js';
import { RARE_PROPS } from '../js/core/scenes.js';

export const MIGRATION = fileURLToPath(new URL('../supabase/migrations/0023_collections.sql', import.meta.url));
export const BEGIN = '-- BEGIN GENERATED by tools/collections-sql.mjs from js/core/collections.js and scenes.js — do not edit by hand';
export const END = '-- END GENERATED';

const lit = (v) => `'${String(v).replace(/'/g, "''")}'`;

export function generatedBlock() {
  const rules = JSON.stringify({ ...COLLECTION_RULES, rare: Object.fromEntries(RARE_PROPS.map((p) => [p.id, { sport: p.sport, fragments: p.fragments }])) });
  return [
    BEGIN,
    'create or replace function public.collection_rules()',
    'returns jsonb language sql immutable set search_path = public as $$',
    `  select ${lit(rules)}::jsonb;`,
    '$$;',
    END,
  ].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  if (process.argv.includes('--print')) {
    console.log(generatedBlock());
  } else {
    const sql = readFileSync(MIGRATION, 'utf8');
    const a = sql.indexOf(BEGIN);
    const b = sql.indexOf(END);
    if (a < 0 || b < 0) throw new Error('markers not found');
    writeFileSync(MIGRATION, sql.slice(0, a) + generatedBlock() + sql.slice(b + END.length));
    console.log(`wrote the generated block of ${MIGRATION}`);
  }
}
