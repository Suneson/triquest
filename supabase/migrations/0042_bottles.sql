-- ---- the roll -------------------------------------------------------------------------------------------

-- a bottle's weight in a tier's chest (bottleWeight())
create or replace function public.bottle_weight(p_tier text, p_id text)
returns int language sql immutable set search_path = public as $$
  select case when coalesce((b ->> 'drops')::boolean, false)
    then coalesce((coalesce(r -> 'weights' -> p_tier, r -> 'weights' -> 'common') ->> ((b ->> 'strength')::int - 1))::int, 0) else 0 end
  from (select public.bottle_rules() as r, public.bottle_rules() -> 'bottles' -> p_id as b) x;
$$;

-- rollBottles(): each slot takes a number for whether it's filled and, if so, one for which bottle
create or replace function public.bottle_roll(p_tier text)
returns text[] language plpgsql volatile set search_path = public as $$
declare
  r     jsonb := public.bottle_rules();
  ids   text[] := array(select jsonb_array_elements_text(r -> 'order'));
  total int := 0;
  out   text[] := '{}';
  ch    float8;
  x     float8;
  w     int;
  pick  text;
  id    text;
begin
  foreach id in array ids loop total := total + public.bottle_weight(p_tier, id); end loop;
  if total = 0 then return out; end if;
  for ch in select x.value::float8 from jsonb_array_elements_text(coalesce(r -> 'slots' -> p_tier, '[]'::jsonb)) x loop
    continue when not (random() < ch);
    x := random() * total;
    pick := null;
    foreach id in array ids loop
      w := public.bottle_weight(p_tier, id);
      continue when w = 0;
      pick := id;
      exit when x < w;
      x := x - w;
    end loop;
    if pick is not null then out := out || pick; end if;
  end loop;
  return out;
end;
$$;

-- tierUp(): the next tier up with an animation; mythic stays mythic
create or replace function public.chest_tier_up(p_tier text)
returns text language plpgsql immutable set search_path = public as $$
declare
  r     jsonb := public.chest_rules();
  tiers text[] := array(select jsonb_array_elements_text(r -> 'tiers'));
  i     int := array_position(tiers, p_tier);
  k     int;
begin
  if i is null then return p_tier; end if;
  for k in i + 1 .. array_length(tiers, 1) loop
    if (r -> 'enabled' ->> tiers[k])::boolean then return tiers[k]; end if;
  end loop;
  return p_tier;
end;
$$;

-- ---- the chests, now with bottles ---------------------------------------------------------------------

create or replace function public.chest_json(c public.reward_chests)
returns json language sql stable set search_path = public as $$
  select json_build_object('id', c.id, 'source', c.source, 'workout_id', c.workout_id, 'day', to_char(c.day, 'YYYY-MM-DD'),
    'difficulty', c.difficulty, 'tier', c.tier, 'xp', c.xp, 'coins', c.coins, 'carbs', c.carbs,
    'bottles', to_json(c.bottles), 'charged', c.charged,
    'created_at', c.created_at, 'opened_at', c.opened_at);
$$;

create or replace function public.chests_grant(p_user uuid)
returns int language plpgsql volatile security definer set search_path = public as $$
declare
  r      jsonb := public.chest_rules();
  e      record;
  made   int;
  tier   text;
  b      record;
  charge bigint;
  cid    bigint;
  n      int := 0;
begin
  -- only ever for yourself (my_chests() is the way in)
  if auth.uid() is distinct from p_user then
    raise exception 'gear:not_yours' using errcode = '42501';
  end if;
  for e in
    select l.id, l.date, l.xp, w.strava_activity_id, public.chest_difficulty(w) as d
    from public.xp_ledger(p_user) l
    join public.workouts w on w.id = l.id and w.user_id = p_user
    where l.date >= (r ->> 'since')::date and l.xp > 0
      and public.chest_minutes(w) >= (r ->> 'minMinutes')::float8
      and not exists (select 1 from public.reward_chests c where c.user_id = p_user
                      and (c.workout_id = l.id or (w.strava_activity_id is not null and c.strava_activity_id = w.strava_activity_id)))
    order by l.date,
             coalesce(w.completed_at, case when w.extra ->> 'gymLoggedAt' ~ '^\d{4}-\d{2}-\d{2}T' then (w.extra ->> 'gymLoggedAt')::timestamptz end) nulls first,
             l.id
  loop
    select count(*) into made from public.reward_chests c where c.user_id = p_user and c.source = 'workout' and c.day = e.date;
    continue when made >= (r ->> 'perDay')::int;
    tier := public.chest_roll(e.d, random());
    -- a Chest Charger waiting: this chest comes one rarity higher, and takes the charge
    select d.id into charge from public.bottle_drinks d
      where d.user_id = p_user and d.bottle = 'chest-charge' and d.chest_id is null
      order by d.drunk_at, d.id limit 1 for update;
    if charge is not null then tier := public.chest_tier_up(tier); end if;
    select * into b from public.chest_bonus(tier, e.xp);
    insert into public.reward_chests (user_id, source, workout_id, strava_activity_id, day, difficulty, tier, xp, coins, carbs, bottles, charged)
    values (p_user, 'workout', e.id, e.strava_activity_id, e.date, e.d, tier, e.xp, b.coins, b.carbs, public.bottle_roll(tier), charge is not null)
    returning id into cid;
    if charge is not null then update public.bottle_drinks set chest_id = cid where id = charge; charge := null; end if;
    n := n + 1;
  end loop;
  return n;
end;
$$;

-- Admins only: a chest of any switched-on tier, for yourself, with its bottles rolled as a real one's.
create or replace function public.admin_gift_chest(p_tier text)
returns json language plpgsql volatile security definer set search_path = public as $$
declare
  uid uuid := auth.uid();
  b   record;
  c   public.reward_chests;
begin
  if uid is null then raise exception 'gear:not_signed_in' using errcode = '28000'; end if;
  if not public.is_app_admin(uid) then raise exception 'gear:not_admin' using errcode = '42501'; end if;
  if coalesce((public.chest_rules() -> 'enabled' ->> p_tier)::boolean, false) is not true then
    raise exception 'gear:chest_tier' using errcode = '22023';
  end if;
  select * into b from public.chest_bonus(p_tier, 0);
  insert into public.reward_chests (user_id, source, day, tier, coins, carbs, bottles)
  values (uid, 'gift', (now() at time zone 'utc')::date, p_tier, b.coins, b.carbs, public.bottle_roll(p_tier))
  returning * into c;
  return public.chest_json(c);
end;
$$;

-- ---- what you hold, and what's working ------------------------------------------------------------------

create or replace function public.bottles_for(p_user uuid)
returns json language sql stable set search_path = public as $$
  with ids as (select jsonb_array_elements_text(public.bottle_rules() -> 'order') as id),
  got as (select x.id, count(*) as n from public.reward_chests c, unnest(c.bottles) x(id)
          where c.user_id = p_user and c.opened_at is not null group by x.id),
  drunk as (select d.bottle as id, count(*) as n from public.bottle_drinks d where d.user_id = p_user group by d.bottle),
  surge as (select max(b.expires_at) as until from public.user_boosts b
            where b.user_id = p_user and b.kind = 'electro-surge' and b.started_at <= now() and now() < b.expires_at),
  brew as (select max(d.drunk_at) + make_interval(hours => (public.bottle_rules() -> 'bottles' -> 'build-brew' ->> 'hours')::int) as until
           from public.bottle_drinks d where d.user_id = p_user and d.bottle = 'build-brew')
  select json_build_object(
    'held', (select json_object_agg(ids.id, coalesce(got.n, 0) - coalesce(drunk.n, 0))
             from ids left join got on got.id = ids.id left join drunk on drunk.id = ids.id),
    'active', json_build_object(
      'chest-charge', exists (select 1 from public.bottle_drinks d where d.user_id = p_user and d.bottle = 'chest-charge' and d.chest_id is null),
      'electro-surge', (select until from surge),
      'build-brew', (select case when until > now() then until end from brew)),
    'fuel_on', exists (select 1 from public.user_boosts b where b.user_id = p_user and b.started_at <= now() and now() < b.expires_at),
    'jobs_running', (select count(*) from public.builder_jobs j where j.user_id = p_user and j.finishes_at > now()));
$$;

-- The app's chests, and now your bottles too. { admin, chests: [...], bottles: bottles_for() }
create or replace function public.my_chests()
returns json language plpgsql volatile security definer set search_path = public as $$
declare
  uid uuid := auth.uid();
begin
  if uid is null then raise exception 'gear:not_signed_in' using errcode = '28000'; end if;
  perform pg_advisory_xact_lock(hashtext('gear:' || uid::text));
  perform public.chests_grant(uid);
  return json_build_object(
    'admin', public.is_app_admin(uid),
    'chests', coalesce((
      select json_agg(public.chest_json(c) order by c.created_at desc, c.id desc)
      from (select * from public.reward_chests
            where user_id = uid and (opened_at is null or opened_at > now() - interval '30 days')
            order by created_at desc, id desc limit 60) c
    ), '[]'::json),
    'bottles', public.bottles_for(uid));
end;
$$;

-- Drink a bottle. Returns bottles_for() as it is afterwards.
create or replace function public.drink_bottle(p_bottle text)
returns json language plpgsql volatile security definer set search_path = public as $$
declare
  uid  uuid := auth.uid();
  br   jsonb := public.bottle_rules() -> 'bottles' -> p_bottle;
  st   json;
begin
  if uid is null then raise exception 'gear:not_signed_in' using errcode = '28000'; end if;
  if br is null or not coalesce((br ->> 'drops')::boolean, false) then raise exception 'gear:unknown_item' using errcode = '22023'; end if;
  perform pg_advisory_xact_lock(hashtext('gear:' || uid::text));
  st := public.bottles_for(uid);
  if coalesce((st -> 'held' ->> p_bottle)::int, 0) < 1 then raise exception 'gear:bottle_none' using errcode = '22023'; end if;
  if p_bottle = 'chest-charge' and (st -> 'active' ->> 'chest-charge')::boolean then
    raise exception 'gear:bottle_active' using errcode = '22023';
  end if;
  if p_bottle in ('electro-surge', 'build-brew') and (st -> 'active' ->> p_bottle) is not null then
    raise exception 'gear:bottle_active' using errcode = '22023';
  end if;
  if p_bottle = 'electro-surge' then
    -- one fuel at a time, as use_gel()
    if (st ->> 'fuel_on')::boolean then raise exception 'gear:fuel_active' using errcode = '22023'; end if;
    insert into public.user_boosts (user_id, kind, started_at, expires_at, multiplier)
    values (uid, 'electro-surge', now(), now() + make_interval(hours => (br ->> 'hours')::int), 1 + (br ->> 'boostBp')::numeric / 10000);
  elsif p_bottle = 'build-brew' then
    if (st ->> 'jobs_running')::int < 1 then raise exception 'gear:idle' using errcode = '22023'; end if;
    -- brewedFinish(): 10x as fast for the hour
    update public.builder_jobs j set finishes_at =
      case when j.finishes_at - now() <= make_interval(hours => (br ->> 'speed')::int * (br ->> 'hours')::int)
           then now() + (j.finishes_at - now()) / (br ->> 'speed')::int
           else j.finishes_at - make_interval(hours => ((br ->> 'speed')::int - 1) * (br ->> 'hours')::int) end
    where j.user_id = uid and j.finishes_at > now();
  end if;
  insert into public.bottle_drinks (user_id, bottle) values (uid, p_bottle);
  return public.bottles_for(uid);
end;
$$;

