-- 0042_bottles.sql: the MOSKE sports bottles, our potions (js/core/bottles.js, docs/BOTTLES.md).
--
--   bottle_rules()       the rules in js/core/bottles.js, as jsonb (generated: tools/bottles-sql.mjs)
--   reward_chests        + bottles (what it holds, rolled when it's made) and charged (a Chest Charger raised it)
--   bottle_drinks        one row per bottle drunk, kept for good; a charge's row takes the chest it raised
--   bottle_roll()        a chest's bottles: its slots, each maybe filled, by strength
--   bottles_for()        what you hold (opened chests' bottles less the drunk ones) and what's working
--   drink_bottle()       drink one: checks you hold it and that it isn't already working, then does it
--   chests_grant(), admin_gift_chest(), chest_json(), my_chests()   as 0027, now with bottles
--
-- The effects:
--   recovery-mix   logged here; the app fills the device's stamina (drills live on the device)
--   electro-surge  a user_boosts row, +50% for 24 h: boost_stamp() (0017) stamps it on workouts like food,
--                  and like any fuel it can't be drunk while another fuel is on
--   build-brew     every running builder job: 10x as fast for an hour, so up to 9 h off each, at once
--   chest-charge   waits; the next workout chest chests_grant() makes comes one rarity higher and takes it
--
-- Nothing is dropped: the new columns default to no bottles, so every chest made before stays as it was.

