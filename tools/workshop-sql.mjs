// workshop-sql.mjs — writes the generated part of supabase/migrations/0022_workshop.sql
// (the workshop rules and the scene props in gear_catalog) from js/core/workshop.js
// and js/core/scenes.js, so the two can't drift. tests/workshop-sql.test.js fails
// if the file and this disagree.
//
//   node tools/workshop-sql.mjs          rewrite the block in place
//   node tools/workshop-sql.mjs --print  print it

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { WORKSHOP_RULES } from '../js/core/workshop.js';
import { PROPS } from '../js/core/scenes.js';

export const MIGRATION = fileURLToPath(new URL('../supabase/migrations/0022_workshop.sql', import.meta.url));
export const BEGIN = '-- BEGIN GENERATED by tools/workshop-sql.mjs from js/core/workshop.js and scenes.js — do not edit by hand';
export const END = '-- END GENERATED';

const lit = (v) => (v == null ? 'null' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);

export function generatedBlock() {
  const rules = JSON.stringify({ ...WORKSHOP_RULES, props: Object.fromEntries(PROPS.map((p) => [p.id, { fitMin: p.fitMin }])) });
  const rows = PROPS.map((p) => `  (${[p.id, 'prop', p.sport, p.slot, null, p.cost, 0, 'coins'].map(lit).join(', ')})`);
  return [
    BEGIN,
    'create or replace function public.workshop_rules()',
    'returns jsonb language sql immutable set search_path = public as $$',
    `  select ${lit(rules)}::jsonb;`,
    '$$;',
    '',
    'insert into public.gear_catalog (id, kind, sport, slot, tier, cost, boost_bp, currency) values',
    rows.join(',\n'),
    'on conflict (id) do update set kind = excluded.kind, sport = excluded.sport, slot = excluded.slot,',
    '  tier = excluded.tier, cost = excluded.cost, boost_bp = excluded.boost_bp, currency = excluded.currency;',
    END,
  ].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  if (process.argv.includes('--print')) {
    console.log(generatedBlock());
  } else {
    const sql = readFileSync(MIGRATION, 'utf8');
    const a = sql.indexOf(BEGIN);
    const b = sql.indexOf(END);
    if (a < 0 || b < 0) throw new Error('markers not found');
    writeFileSync(MIGRATION, sql.slice(0, a) + generatedBlock() + sql.slice(b + END.length));
    console.log(`wrote the generated block of ${MIGRATION}`);
  }
}
