-- One athlete's sessions as a challenge sees them, with whole metres.
create type public.ch_row as (id text, date date, type text, m numeric, mov numeric, vmax numeric, sport_type text,
  manual boolean, trainer boolean, earns boolean, strava boolean, rest boolean,
  elev numeric, best jsonb, segs jsonb, xp numeric);

create or replace function public.challenge_rows(p_user uuid)
returns setof public.ch_row
language sql stable set search_path = public as $$
  select b.id, b.date, b.type, round(b.dist_m), b.mov, b.vmax, b.sport_type, b.manual, b.trainer, b.earns, b.strava, b.rest,
         greatest(b.elev, 0), b.best, b.segs, public.session_xp(w)
  from public.feat_base(p_user) b join public.workouts w on w.id = b.id and w.user_id = p_user;
$$;

-- qualifies(): Strava, earned, not typed in, in the window, the sport, not on a
-- rest day, outdoors for the volume and speed kinds, inside the feat bounds.
create or replace function public.challenge_counts(c public.challenges, r public.ch_row)
returns boolean language sql stable set search_path = public as $$
  select r.type <> 'gym' and r.earns and r.strava and not r.manual
     and r.date between c.starts_on and c.ends_on
     and (case when c.sport = 'any' then r.type in ('run', 'bike', 'swim', 'brick') else r.type = c.sport end)
     and not r.rest
     and (c.kind not in ('distance', 'fastest', 'longest', 'climb', 'segment')
          or (public.feat_rules() -> 'sportTypes' ? r.type and not r.trainer
              and coalesce(public.feat_rules() -> 'sportTypes' -> r.type ? r.sport_type, false)))
     and public.feat_bound(r.type, r.m, r.mov, r.vmax) is null;
$$;

-- day caps, then 1.3 × the athlete's own weekly average (never below the floor) on each 7-day block
create or replace function public.challenge_capped(c public.challenges, p_user uuid, p_climb boolean)
returns table (total numeric, cut boolean, sessions text[])
language plpgsql stable set search_path = public as $$
declare
  cr jsonb := public.challenge_rules();
  day_cap numeric := case when p_climb then (cr -> 'climbDayCap' ->> c.sport)::numeric else (cr -> 'dayCap' ->> c.sport)::numeric end;
  floor_ numeric := case when p_climb then (cr -> 'climbWeekFloor' ->> c.sport)::numeric else (cr -> 'weekFloor' ->> c.sport)::numeric end;
  before numeric;
  ceil_ numeric;
begin
  select coalesce(sum(case when p_climb then x.elev else x.m end), 0) into before
  from public.challenge_rows(p_user) x
  where x.type = c.sport and x.date >= c.starts_on - 28 and x.date < c.starts_on and x.earns and x.strava and not x.manual;
  ceil_ := greatest(floor_, floor(before * (cr ->> 'weekGrowthBp')::numeric / 40000));
  return query
    with q as (
      select x.* from public.challenge_rows(p_user) x where public.challenge_counts(c, x)
    ), d as (
      select q.date, sum(case when p_climb then q.elev else q.m end) as v from q group by q.date
    ), wk as (
      select (d.date - c.starts_on) / 7 as w, sum(least(day_cap, d.v)) as v, bool_or(d.v > day_cap) as dcut from d group by 1
    )
    select coalesce(sum(least(ceil_, wk.v)), 0), coalesce(bool_or(wk.dcut or wk.v > ceil_), false),
           (select array_agg(q.id order by q.id) from q)
    from wk;
end;
$$;

-- scoreFor(): (score, sessions, cut); score null for a no-show. Whole numbers in
-- the unit the app shows: 10 m, 1 m, 1 XP, 1 session, 1 second.
create or replace function public.challenge_score(c public.challenges, p_user uuid)
returns table (score bigint, sessions text[], cut boolean)
language plpgsql stable set search_path = public as $$
declare
  cr jsonb := public.challenge_rules();
  n int;
  t numeric; ct boolean; ids text[];
  d numeric;
  capsec numeric;
  bestsec numeric; bestid text;
begin
  select count(*) into n from public.challenge_rows(p_user) x where public.challenge_counts(c, x);
  if n = 0 then return query select null::bigint, '{}'::text[], false; return; end if;
  if c.kind in ('distance', 'climb') then
    select k.total, k.cut, k.sessions into t, ct, ids from public.challenge_capped(c, p_user, c.kind = 'climb') k;
    return query select (case when c.kind = 'distance' then round(t / 10) else round(t) end)::bigint, ids, ct;
    return;
  elsif c.kind = 'xp' then
    return query select sum(x.xp)::bigint, array_agg(x.id order by x.id), false
      from public.challenge_rows(p_user) x where public.challenge_counts(c, x);
    return;
  elsif c.kind = 'sessions' then
    return query select count(distinct x.date)::bigint, array_agg(x.id order by x.id), false
      from public.challenge_rows(p_user) x where public.challenge_counts(c, x);
    return;
  elsif c.kind = 'longest' then
    capsec := least((c.params ->> 'targetMin')::numeric, (cr -> 'longestMaxMin' ->> c.sport)::numeric) * 60;
    select max(round(x.mov)) into bestsec from public.challenge_rows(p_user) x where public.challenge_counts(c, x);
    return query select least(capsec, bestsec)::bigint,
      (select array_agg(x.id order by x.id) from public.challenge_rows(p_user) x where public.challenge_counts(c, x)), bestsec > capsec;
    return;
  elsif c.kind = 'fastest' then
    d := (cr -> 'fastest' -> c.sport ->> (c.params ->> 'dist'))::numeric;
    if d is null then return query select null::bigint, '{}'::text[], false; return; end if;
    select s.sec, s.id into bestsec, bestid from (
      select x.id, case
               when c.sport = 'run' and coalesce((x.best ->> (c.params ->> 'dist'))::numeric, 0) > 0 then (x.best ->> (c.params ->> 'dist'))::numeric
               when x.m >= d and x.mov > 0 then round(x.mov * d / x.m)
             end as sec, x.date
      from public.challenge_rows(p_user) x where public.challenge_counts(c, x)
    ) s where s.sec is not null order by s.sec, s.date, s.id limit 1;
    if bestsec is null then return query select null::bigint, '{}'::text[], false; return; end if;
    return query select bestsec::bigint, array[bestid], false;
    return;
  elsif c.kind = 'segment' then
    select e.sec, e.id into bestsec, bestid from (
      select x.id, (s ->> 'sec')::numeric as sec, x.date
      from public.challenge_rows(p_user) x, jsonb_array_elements(x.segs) s
      where public.challenge_counts(c, x) and (s ->> 'id')::numeric = (c.params ->> 'segmentId')::numeric
        and coalesce((s ->> 'sec')::numeric, 0) > 0
    ) e order by e.sec, e.date, e.id limit 1;
    if bestsec is null then return query select null::bigint, '{}'::text[], false; return; end if;
    return query select bestsec::bigint, array[bestid], false;
    return;
  end if;
  return query select null::bigint, '{}'::text[], false;
  return;
end;
$$;

