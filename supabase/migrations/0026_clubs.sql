-- your club: who's in it (names only), this week's total against the target,
-- and the relay. Totals only: nothing about anyone's days.
create or replace function public.club_board()
returns json language plpgsql stable security definer set search_path = public as $$
declare
  uid  uuid := auth.uid();
  cid  bigint := public.club_of(auth.uid());
  wk   date := (now() at time zone 'utc')::date - (extract(isodow from (now() at time zone 'utc')::date)::int - 1);
  rel  public.club_relays;
  out  json;
begin
  if uid is null or cid is null then return null; end if;
  select * into rel from public.club_relays where club_id = cid order by started_at desc, id desc limit 1;
  select json_build_object(
    'id', c.id, 'name', c.name, 'crest', c.crest, 'created_at', c.created_at,
    'me', (select role from public.club_members where club_id = cid and user_id = uid and left_at is null),
    'members', (select coalesce(json_agg(json_build_object('user_id', m.user_id, 'role', m.role,
        'display_name', coalesce(p.display_name, 'Athlete'), 'username', p.username, 'avatar', p.settings ->> 'avatar') order by m.joined_at, m.id), '[]'::json)
      from public.club_members m left join public.profiles p on p.id = m.user_id
      where m.club_id = cid and m.left_at is null),
    'week', wk,
    'week_minutes', public.club_week_minutes(cid, wk),
    'target_minutes', (select t.minutes from public.club_targets t where t.club_id = cid and t.week = wk),
    'relay', case when rel.id is null then null else json_build_object('route_id', rel.route_id, 'started_at', rel.started_at,
      'km', public.club_relay_km(cid, rel.started_at)) end,
    'relays_done', greatest(0, (select count(*) from public.club_relays where club_id = cid) - 1)
  ) into out from public.clubs c where c.id = cid;
  return out;
end;
$$;

-- clubs by name, for anyone signed in: name, crest and how many are in it
create or replace function public.list_clubs(p_query text default '')
returns table (id bigint, name text, crest text, members int)
language sql stable security definer set search_path = public as $$
  select c.id, c.name, c.crest, (select count(*)::int from public.club_members m where m.club_id = c.id and m.left_at is null)
  from public.clubs c
  where auth.uid() is not null
    and (coalesce(p_query, '') = '' or c.name ilike '%' || replace(replace(btrim(p_query), '%', ''), '_', '') || '%')
  order by 4 desc, c.name
  limit 30;
$$;

-- your open invites, with the club's name and crest
create or replace function public.my_club_invites()
returns table (id bigint, club_id bigint, name text, crest text, members int, invited_by text, created_at timestamptz)
language sql stable security definer set search_path = public as $$
  select i.id, c.id, c.name, c.crest,
         (select count(*)::int from public.club_members m where m.club_id = c.id and m.left_at is null),
         coalesce(p.display_name, 'Athlete'), i.created_at
  from public.club_invites i
  join public.clubs c on c.id = i.club_id
  left join public.profiles p on p.id = i.invited_by
  where i.user_id = auth.uid() and i.responded_at is null
  order by i.created_at desc;
$$;

