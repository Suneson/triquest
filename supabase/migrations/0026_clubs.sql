  id        bigint generated always as identity primary key,
  club_id   bigint not null references public.clubs (id) on delete cascade,
  user_id   uuid not null references auth.users (id) on delete cascade,
  role      text not null default 'member' check (role in ('owner', 'member')),
  joined_at timestamptz not null default now(),
  left_at   timestamptz
);
create unique index if not exists club_members_one_club on public.club_members (user_id) where left_at is null;
create index if not exists club_members_club on public.club_members (club_id) where left_at is null;

create table if not exists public.club_invites (
  id           bigint generated always as identity primary key,
  club_id      bigint not null references public.clubs (id) on delete cascade,
  user_id      uuid not null references auth.users (id) on delete cascade,
  invited_by   uuid references auth.users (id) on delete set null,
  created_at   timestamptz not null default now(),
  responded_at timestamptz,
  accepted     boolean
);
create unique index if not exists club_invites_open on public.club_invites (club_id, user_id) where responded_at is null;

create table if not exists public.club_targets (
  club_id bigint not null references public.clubs (id) on delete cascade,
  week    date not null check (extract(isodow from week) = 1),
  minutes int not null check (minutes > 0),
  set_by  uuid references auth.users (id) on delete set null,
  set_at  timestamptz not null default now(),
  primary key (club_id, week)
);

create table if not exists public.club_relays (
  id         bigint generated always as identity primary key,
  club_id    bigint not null references public.clubs (id) on delete cascade,
  route_id   text not null,
  started_by uuid references auth.users (id) on delete set null,
  started_at timestamptz not null default now()
);
create index if not exists club_relays_club on public.club_relays (club_id, started_at desc);

