-- gear_bp_sport() as in 0022, plus bonusBp for every star taken by p_at
create or replace function public.gear_bp_sport(p_user uuid, p_sport text, p_at timestamptz)
returns int language sql stable set search_path = public as $$
  select least((public.gear_rules() ->> 'sportCapBp')::int, coalesce(sum(c.boost_bp), 0))::int
       + (select count(*)::int from public.user_prestige p
          where p.user_id = p_user and p.sport = p_sport and p.created_at <= p_at)
         * (public.collection_rules() -> 'prestige' ->> 'bonusBp')::int
  from (
    select c.slot, max(c.tier) as tier
    from (
      select g.item_id from public.user_gear g where g.user_id = p_user and g.acquired_at <= p_at
      union
      select j.item_id from public.workshop_jobs j where j.user_id = p_user and j.state <> 'cancelled' and j.finishes_at <= p_at
    ) o join public.gear_catalog c on c.id = o.item_id
    where c.kind = 'gear' and c.sport = p_sport
    group by c.slot
  ) o
  join public.gear_catalog c on c.kind = 'gear' and c.sport = p_sport and c.slot = o.slot and c.tier = o.tier;
$$;

-- levelFromTotalXp(): cost(L→L+1) = round(100 × L^1.6), in numeric so it rounds like JS
create or replace function public.level_from_xp(p_xp numeric)
returns int language plpgsql immutable set search_path = public as $$
declare lvl int := 1; need numeric := 0;
begin
  loop
    need := need + round(100 * power(lvl::numeric, 1.6));
    exit when need > greatest(0, floor(p_xp));
    lvl := lvl + 1;
  end loop;
  return lvl;
end;
$$;

-- ---- blueprints ----------------------------------------------------------------------

create or replace function public.blueprint_fragments(p_user uuid)
returns table (earned int, spent int, free int)
language sql stable set search_path = public as $$
  with e as (
    select (count(*) * (public.collection_rules() ->> 'fragmentPerMission')::int)::int as n
    from public.quest_completions q
    where q.user_id = p_user and q.day >= (public.collection_rules() ->> 'fragmentsSince')::date
  ), s as (
    select coalesce(sum(b.fragments), 0)::int as n from public.user_blueprints b where b.user_id = p_user
  )
  select e.n, s.n, greatest(0, e.n - s.n) from e, s;
$$;

create or replace function public.build_blueprint(p_item text)
returns json language plpgsql security definer set search_path = public as $$
declare
  uid  uuid := auth.uid();
  cost int := (public.collection_rules() -> 'rare' -> p_item ->> 'fragments')::int;
  f    record;
begin
  if uid is null then raise exception 'gear:not_signed_in' using errcode = '28000'; end if;
  if cost is null then raise exception 'gear:unknown_item' using errcode = '22023'; end if;
  perform pg_advisory_xact_lock(hashtext('gear:' || uid::text));
  if exists (select 1 from public.user_blueprints where user_id = uid and item_id = p_item) then
    raise exception 'gear:owned' using errcode = '22023';
  end if;
  select * into f from public.blueprint_fragments(uid);
  if f.free < cost then raise exception 'gear:fragments_short' using errcode = '22023'; end if;
  insert into public.user_blueprints (user_id, item_id, fragments) values (uid, p_item, cost);
  return json_build_object('item_id', p_item, 'free', f.free - cost);
end;
$$;

-- ---- prestige ------------------------------------------------------------------------

create or replace function public.prestige(p_sport text)
returns json language plpgsql security definer set search_path = public as $$
declare
  uid   uuid := auth.uid();
  pr    jsonb := public.collection_rules() -> 'prestige';
  xp    bigint;
  base  bigint;
  stars int;
begin
  if uid is null then raise exception 'gear:not_signed_in' using errcode = '28000'; end if;
  if p_sport not in ('bike', 'swim', 'run', 'gym') then raise exception 'gear:unknown_item' using errcode = '22023'; end if;
  perform pg_advisory_xact_lock(hashtext('gear:' || uid::text));
  select count(*)::int, coalesce(max(p.xp_at), 0) into stars, base
  from public.user_prestige p where p.user_id = uid and p.sport = p_sport;
  if stars >= (pr ->> 'maxStars')::int then raise exception 'gear:prestige_max' using errcode = '22023'; end if;
  select coalesce(sum(b.boosted), 0) into xp from public.boosted_sport_xp(uid) b where b.type = p_sport;
  if public.level_from_xp(xp - base) < (pr ->> 'level')::int then
    raise exception 'gear:prestige_level' using errcode = '22023';
  end if;
  insert into public.user_prestige (user_id, sport, star, xp_at) values (uid, p_sport, stars + 1, xp);
  return json_build_object('sport', p_sport, 'star', stars + 1, 'xp_at', xp);
end;
$$;

