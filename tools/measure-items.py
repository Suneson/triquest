"""measure-items.py — how each room item's picture stands, so the diorama can
set it down inside its footprint (js/core/item-fit.js, generated).

    python3 tools/measure-items.py

For every picture: w = the opaque width as a share of the picture's width,
mid = the opaque middle (0–1 across), pad = the empty rows under it as a share
of the height. Build-time only (Pillow, numpy).
"""
import glob, json, os
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILES = sorted(glob.glob(os.path.join(ROOT, 'icons/Pixelart/NEW/ITEMS/*.webp'))) + [
    os.path.join(ROOT, 'icons/Pixelart/GEAR/bike-power-t3.png'),
] + sorted(glob.glob(os.path.join(ROOT, 'icons/Pixelart/BIKE/CHARACTERS/bikelvl*_char*.webp')))

out = {}
for f in FILES:
    im = Image.open(f).convert('RGBA')
    a = np.asarray(im)[..., 3] > 40
    H, W = a.shape
    rows = np.where(a.any(1))[0]
    cols = np.where(a.any(0))[0]
    out[os.path.relpath(f, ROOT)] = {
        'w': round((cols[-1] - cols[0] + 1) / W, 3),
        'mid': round((cols[0] + cols[-1] + 1) / 2 / W, 3),
        'pad': round((H - 1 - rows[-1]) / H, 3),
    }

js = """// item-fit.js — how each room item's picture stands (generated by
// tools/measure-items.py; do not edit by hand). w: the opaque width as a share
// of the picture's, mid: its middle (0–1 across), pad: the empty rows under it.
// The diorama uses it to set every item down inside its footprint.

export const ITEM_FIT = %s;

/** A picture's measures, or a plain full-width one. */
export const fitOf = (src) => ITEM_FIT[src] || { w: 1, mid: 0.5, pad: 0 };
""" % json.dumps(out, indent=2)
open(os.path.join(ROOT, 'js/core/item-fit.js'), 'w').write(js)
print(len(out), 'pictures')
