-- 0017: a gel boosts your next workout instead of the next few hours
-- (docs/GEAR.md §12). Food stays on a clock.
--
-- A gel taken is a user_boosts row with until_next = true and expires_at =
-- 'infinity': it is "on" (so nothing else can be taken) until the next
-- session that earns XP reaches the server. That session's stamp gets the
-- whole gel, the row records which session (workout_id) and closes
-- (expires_at = then). A session that ended more than graceHours before the
-- gel was taken can't use it, so an old activity synced late doesn't.

alter table public.user_boosts add column if not exists until_next boolean not null default false;
alter table public.user_boosts add column if not exists workout_id text; -- no foreign key: it is set while the session row is still being inserted
create index if not exists user_boosts_waiting on public.user_boosts (user_id, started_at) where until_next and workout_id is null;

