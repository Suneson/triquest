// collections.js — collections, blueprints and prestige (docs/LOOP.md §4). Pure.
//
//   - Collections: a sport's four slots at tier 1 or better is its tier-1 set,
//     and so on to tier 3. A set completes the moment its last piece is yours
//     (a finished workshop job counts from its finish) and pays a one-off coin
//     bonus, and a plaque goes up on the sport's board. Gear is never taken
//     away, so a set once complete stays complete.
//   - Blueprints: every mission you complete is a fragment. You choose which
//     rare prop to work towards and see how many fragments are left; when you
//     have enough you build it. Nothing is random: the same missions give the
//     same fragments to everyone, and every target shows its price up front.
//   - Prestige: at PRESTIGE.level in a discipline you may reset its level for
//     a star on the board and a small permanent boost in that discipline. It's
//     opt-in and the app never suggests it. Ranks never see it (base XP only);
//     the scenery you reached stays.
//
// The same rules run on the server (0023_collections.sql, generated by
// tools/collections-sql.mjs), so the client and the server can't disagree.

import { SLOTS, SPORTS, gearById, GEAR_SINCE } from './gear.js';
import { RARE_PROPS, rareById } from './scenes.js';
import { levelFromTotalXp } from './scoring.js';

export const COLLECTION_RULES = {
  setCoins: [0, 40, 140, 340],   // the bonus for completing a sport's tier-1 / 2 / 3 set (~10% of the set)
  fragmentsSince: GEAR_SINCE,    // missions completed on or after this day are fragments
  fragmentPerMission: 1,
  prestige: { level: 10, maxStars: 5, bonusBp: 100 }, // +1% per star, outside the gear cap
};
export const PRESTIGE = COLLECTION_RULES.prestige;
export const SET_TIERS = [1, 2, 3];

const ms = (s) => {
  const x = Date.parse(s);
  return Number.isFinite(x) ? x : null;
};

/**
 * When each slot first reached `tier` or better: { slot: ms | null }. Inventory
 * rows are { item_id, acquired_at }; a row with no time counts as long ago.
 */
function slotTimes(inventory, sport, tier) {
  const out = Object.fromEntries((SLOTS[sport] || []).map((s) => [s, null]));
  for (const row of inventory || []) {
    const e = gearById(row?.item_id);
    if (!e || e.sport !== sport || e.tier < tier || !(e.slot in out)) continue;
    const at = ms(row.acquired_at) ?? 0;
    if (out[e.slot] == null || at < out[e.slot]) out[e.slot] = at;
  }
  return out;
}

/**
 * A sport's three sets, from the start, as frames to fill:
 * [{ sport, tier, slots: [{ slot, done }], have, done, at, coins }].
 */
export function collectionsFor(sport, inventory) {
  return SET_TIERS.map((tier) => {
    const times = slotTimes(inventory, sport, tier);
    const slots = (SLOTS[sport] || []).map((slot) => ({ slot, done: times[slot] != null }));
    const have = slots.filter((s) => s.done).length;
    const done = have === slots.length && slots.length > 0;
    return {
      sport, tier, slots, have, done,
      at: done ? new Date(Math.max(...Object.values(times))).toISOString() : null,
      coins: COLLECTION_RULES.setCoins[tier],
    };
  });
}

/** Every completed set with its bonus, in time order: [{ sport, tier, at, coins }]. */
export function collectionAwards(inventory) {
  return SPORTS.flatMap((s) => collectionsFor(s, inventory).filter((c) => c.done))
    .map(({ sport, tier, at, coins }) => ({ sport, tier, at, coins }))
    .sort((a, b) => a.at.localeCompare(b.at) || SPORTS.indexOf(a.sport) - SPORTS.indexOf(b.sport) || a.tier - b.tier);
}

// ---- blueprints ---------------------------------------------------------------------

/** Fragments earned: one per mission completed since fragmentsSince. */
export const fragmentsEarned = (quests) => (quests || [])
  .filter((q) => String(q?.day || '') >= COLLECTION_RULES.fragmentsSince).length * COLLECTION_RULES.fragmentPerMission;

/**
 * Where your blueprints stand: { earned, spent, free, built: Set, target, left }.
 * `built` is [{ item_id }] (what you've already built); `target` the rare
 * prop you're working towards (or null).
 */
export function blueprintState(quests, built, targetId = null) {
  const have = new Set((built || []).map((b) => b.item_id));
  const earned = fragmentsEarned(quests);
  const spent = [...have].reduce((n, id) => n + (rareById(id)?.fragments || 0), 0);
  const free = Math.max(0, earned - spent);
  const target = rareById(targetId) && !have.has(targetId) ? rareById(targetId) : null;
  return { earned, spent, free, built: have, target, left: target ? Math.max(0, target.fragments - free) : null };
}

/** Can this rare prop be built now? { ok, reason: 'unknown' | 'built' | 'short' }. */
export function canBuild(itemId, quests, built) {
  const r = rareById(itemId);
  if (!r) return { ok: false, reason: 'unknown' };
  const s = blueprintState(quests, built);
  if (s.built.has(itemId)) return { ok: false, reason: 'built' };
  if (s.free < r.fragments) return { ok: false, reason: 'short' };
  return { ok: true };
}

export { RARE_PROPS };

// ---- prestige ------------------------------------------------------------------------

/** Your stars in a sport, oldest first. `prestige` is [{ sport, star, xp_at, created_at }]. */
export const starsIn = (prestige, sport) => (prestige || []).filter((p) => p.sport === sport).sort((a, b) => a.star - b.star);

/** The XP a sport's level counts from: the XP at its last reset (0 before any). */
export const prestigeFloor = (prestige, sport) => {
  const s = starsIn(prestige, sport);
  return s.length ? Number(s[s.length - 1].xp_at) || 0 : 0;
};

/**
 * A sport's level after any resets: levelFromTotalXp() over the XP since the
 * last one, plus { stars, artLevel }. The scenery stays at the highest level
 * you ever reached (`artLevel`), so a reset never takes it away.
 */
export function sportLevel(xp, prestige, sport) {
  const stars = starsIn(prestige, sport).length;
  const p = levelFromTotalXp(Math.max(0, (Number(xp) || 0) - prestigeFloor(prestige, sport)));
  return { ...p, stars, artLevel: stars ? Math.max(p.level, PRESTIGE.level) : p.level };
}

/** May this sport be reset now? { ok, reason: 'level' | 'max' }. */
export function canPrestige(xp, prestige, sport) {
  const s = sportLevel(xp, prestige, sport);
  if (s.stars >= PRESTIGE.maxStars) return { ok: false, reason: 'max' };
  if (s.level < PRESTIGE.level) return { ok: false, reason: 'level' };
  return { ok: true };
}

/** The permanent boost from stars earned by `at` (basis points; outside the gear cap). */
export function prestigeBp(prestige, sport, at = null) {
  const atMs = at == null ? Infinity : ms(at);
  return starsIn(prestige, sport).filter((p) => atMs === Infinity || (ms(p.created_at) ?? Infinity) <= atMs).length * PRESTIGE.bonusBp;
}
