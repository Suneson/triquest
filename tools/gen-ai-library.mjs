// gen-ai-library.mjs — write the exercise library the ai-plan Edge Function
// shows the model (ids, names, main muscle, equipment). The function runs on
// Deno and can't import js/core, so it gets this generated copy; a test fails
// when it drifts from js/core/exercises.js.
//
// Usage: node tools/gen-ai-library.mjs

import { writeFileSync } from 'node:fs';
import { EXERCISES } from '../js/core/exercises.js';

export function libraryTs() {
  const rows = EXERCISES.map((e) => `  { id: ${JSON.stringify(e.id)}, name: ${JSON.stringify(e.name)}, muscle: ${JSON.stringify(e.muscle)}, equipment: ${JSON.stringify(e.equipment)} },`);
  return `// GENERATED by tools/gen-ai-library.mjs from js/core/exercises.js — do not edit.
/** @type {{ id: string, name: string, muscle: string, equipment: string }[]} */
export const EXERCISE_LIBRARY = [
${rows.join('\n')}
];
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync('supabase/functions/ai-plan/exercise-library.js', libraryTs());
  console.log(`${EXERCISES.length} exercises → supabase/functions/ai-plan/exercise-library.js`);
}
