// feats-sql.mjs — writes the generated part of supabase/migrations/0018_feats.sql
// (the feat rules and the catalog) from js/core/feats.js, so the two can't
// drift. tests/feats-sql.test.js fails if the file and this disagree.
//
//   node tools/feats-sql.mjs          rewrite the block in place
//   node tools/feats-sql.mjs --print  print it

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { FEATS, FEAT_RULES, FEATS_SINCE, MANUAL_SINCE, LIFTS } from '../js/core/feats.js';

export const MIGRATION = fileURLToPath(new URL('../supabase/migrations/0018_feats.sql', import.meta.url));
export const BEGIN = '-- BEGIN GENERATED by tools/feats-sql.mjs from js/core/feats.js — do not edit by hand';
export const END = '-- END GENERATED';

const lit = (v) => (v == null ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const PARAMS = new Set(['id', 'sport', 'tier', 'kind', 'repeatable', 'reward', 'name', 'blurb', 'art']);

export function generatedBlock() {
  const rules = JSON.stringify({ ...FEAT_RULES, since: FEATS_SINCE, manualSince: MANUAL_SINCE, lifts: LIFTS });
  const rows = FEATS.map((f, i) => {
    const params = Object.fromEntries(Object.entries(f).filter(([k]) => !PARAMS.has(k)));
    return `  (${[f.id, f.sport, f.tier, f.kind, JSON.stringify(params), f.repeatable, f.reward, i + 1].map(lit).join(', ')})`;
  });
  return [
    BEGIN,
    'create or replace function public.feat_rules()',
    'returns jsonb language sql immutable set search_path = public as $$',
    `  select ${lit(rules)}::jsonb;`,
    '$$;',
    '',
    'insert into public.feats (id, sport, tier, kind, params, repeatable, reward, ord) values',
    rows.join(',\n'),
    'on conflict (id) do update set sport = excluded.sport, tier = excluded.tier, kind = excluded.kind,',
    '  params = excluded.params, repeatable = excluded.repeatable, reward = excluded.reward, ord = excluded.ord;',
    END,
  ].join('\n');
}

/** The migration text with its generated block replaced. */
export function withBlock(sql) {
  const a = sql.indexOf(BEGIN);
  const b = sql.indexOf(END);
  if (a < 0 || b < a) throw new Error('0018_feats.sql has no generated block markers');
  return sql.slice(0, a) + generatedBlock() + sql.slice(b + END.length);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes('--print')) console.log(generatedBlock());
  else {
    writeFileSync(MIGRATION, withBlock(readFileSync(MIGRATION, 'utf8')));
    console.log('wrote the generated block of', MIGRATION);
  }
}
