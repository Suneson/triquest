-- 0025: weekly missions, seasons and the daily stall (docs/LOOP.md §5). Mirrors
-- js/core/missions.js and js/core/stall.js; tests/missions-sql.test.js runs both
-- over the same cases.
--
--   - Weekly missions: each week (Monday–Sunday) has two training missions and
--     one rest or recovery mission, rotating through a fixed pool in a fixed
--     order (week_missions()). claim_mission() checks the week's verified work
--     (earns(), the XP rule) and pays MISSION_RULES.reward once, in that week or
--     the one after. Rest missions pay the same as training ones. A rest day
--     counts once it's over (by the server's UTC date).
--   - Wallet: paid missions are an earning in wallet_fold() (rank 5), from the
--     moment they were paid, so balances stay derived.
--   - Seasons need nothing here: a season's board and its kit colourway are
--     worked out from mission_claims on the device (seasons.js), and nothing
--     earned is ever removed.
--   - The stall: one decor item a day (UTC), the same for everyone, walking
--     STALL_ITEMS in order (stall_item()). buy_stall() sells only the day's
--     item, for coins, owned at once; buy_gear() refuses decor. Decor rows are
--     props with slot 'decor', so the catalog's kind check stays as it is.
--   - Written without DROP or REVOKE: who may read what is checked inside each
--     function, so the migration applies without a destructive-statement prompt.

