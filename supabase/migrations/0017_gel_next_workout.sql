-- ---- the stamp: food windows only; a gel is added by the trigger below -------

create or replace function public.boost_stamp(w public.workouts, p_now timestamptz)
returns jsonb language sql stable set search_path = public as $$
  with sp as (select s, e from public.session_span(w)),
  g as (
    select coalesce(sum(
             case
               when sp.e <= sp.s then
                 case when sp.s >= b.started_at and sp.s < b.expires_at then round((b.multiplier - 1) * 10000) else 0 end
               else round(round((b.multiplier - 1) * 10000)
                          * greatest(0, extract(epoch from (least(sp.e, b.expires_at) - greatest(sp.s, b.started_at))))
                          / extract(epoch from (sp.e - sp.s)))
             end), 0) as bp
    from sp, public.user_boosts b
    where b.user_id = w.user_id and not b.until_next
      and p_now <= b.expires_at + make_interval(hours => (public.gear_rules() -> 'fuel' ->> 'graceHours')::int)
  )
  select jsonb_build_object(
    'gear_bp', public.gear_bp_at(w.user_id, w.type, (select e from sp)),
    'gel_bp', least((select max((v ->> 'boostBp')::int) from jsonb_each(public.gear_rules() -> 'fuel' -> 'items') x(k, v)),
                    coalesce((select bp from g), 0))::int);
$$;

-- Stamps a session once, the first time it earns, and hands it the oldest
-- waiting gel that fits. Security definer so it can close the gel row (users
-- can only read user_boosts); nobody can call it directly.
create or replace function public.workouts_stamp_boost()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  gel public.user_boosts;
  cap int;
begin
  if tg_op = 'UPDATE' then
    new.boost := old.boost;
    new.first_earned_at := old.first_earned_at;
  else
    new.boost := null;
    new.first_earned_at := null;
  end if;
  if new.first_earned_at is null and public.earns(new) then
    new.first_earned_at := now();
    new.boost := public.boost_stamp(new, now());
    select b.* into gel
    from public.user_boosts b
    where b.user_id = new.user_id and b.until_next and b.workout_id is null and b.started_at <= now()
      and coalesce((select e from public.session_span(new)), now())
          >= b.started_at - make_interval(hours => (public.gear_rules() -> 'fuel' ->> 'graceHours')::int)
    order by b.started_at, b.id
    limit 1
    for update of b;
    if found then
      cap := (select max((v ->> 'boostBp')::int) from jsonb_each(public.gear_rules() -> 'fuel' -> 'items') x(k, v));
      update public.user_boosts
        set workout_id = new.id, expires_at = greatest(now(), gel.started_at + interval '1 millisecond')
        where id = gel.id;
      new.boost := jsonb_set(new.boost, '{gel_bp}',
        to_jsonb(least(cap, (new.boost ->> 'gel_bp')::int + round((gel.multiplier - 1) * 10000)::int)));
    end if;
  end if;
  return new;
end;
$$;
revoke execute on function public.workouts_stamp_boost() from public, anon, authenticated;

