-- 0022: the workshop (docs/LOOP.md §1) and scene props (§2). Mirrors
-- js/core/workshop.js; tests/workshop-sql.test.js runs both over the same cases.
--
--   - Buying a gear tier or a prop pays at once and queues a job. The job's
--     start and finish come from this server's clock, never the device's.
--   - The item is yours from the job's finish: workshop_settle() writes it to
--     user_gear with acquired_at = finishes_at, and gear_bp_sport() counts a
--     finished job even before it is settled, so a session's boost never
--     depends on when anyone looked.
--   - Removing a job that hasn't started refunds it all. Mid-fit, the first
--     cancel ever refunds it all, later ones cancelRefundBp. A refund lowers the
--     purchase's own coin_spends row, so the wallet needs no new event.
--   - A gel finishes the job being fitted; the gel is used up (fuel_held()).
--   - One bay; a second with the bay2Feat feat.

