// missions-sql.mjs — writes the generated part of supabase/migrations/0025_missions.sql
// (the weekly mission rotation and rewards, the daily stall and its catalog rows)
// from js/core/missions.js and js/core/stall.js, so the two can't drift.
// tests/missions-sql.test.js fails if the file and this disagree.
//
//   node tools/missions-sql.mjs          rewrite the block in place
//   node tools/missions-sql.mjs --print  print it

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { MISSION_RULES, TRAINING_MISSIONS, REST_MISSIONS } from '../js/core/missions.js';
import { STALL_RULES, STALL_ITEMS } from '../js/core/stall.js';

export const MIGRATION = fileURLToPath(new URL('../supabase/migrations/0025_missions.sql', import.meta.url));
export const BEGIN = '-- BEGIN GENERATED by tools/missions-sql.mjs from js/core/missions.js and stall.js — do not edit by hand';
export const END = '-- END GENERATED';

const lit = (v) => `'${String(v).replace(/'/g, "''")}'`;

export function generatedBlock() {
  const missions = JSON.stringify({
    since: MISSION_RULES.since, training: MISSION_RULES.training, reward: MISSION_RULES.reward, claimWindow: MISSION_RULES.claimWindow,
    trainingIds: TRAINING_MISSIONS.map((m) => m.id), restIds: REST_MISSIONS.map((m) => m.id),
    targets: Object.fromEntries([...TRAINING_MISSIONS, ...REST_MISSIONS].map((m) => [m.id, m.target])),
  });
  const stall = JSON.stringify({ since: STALL_RULES.since, items: STALL_ITEMS.map((i) => i.id) });
  return [
    BEGIN,
    'create or replace function public.mission_rules()',
    'returns jsonb language sql immutable set search_path = public as $$',
    `  select ${lit(missions)}::jsonb;`,
    '$$;',
    'create or replace function public.stall_rules()',
    'returns jsonb language sql immutable set search_path = public as $$',
    `  select ${lit(stall)}::jsonb;`,
    '$$;',
    "alter table public.gear_catalog drop constraint if exists gear_catalog_kind_check;",
    "alter table public.gear_catalog add constraint gear_catalog_kind_check check (kind in ('gear', 'kit', 'gel', 'food', 'prop', 'decor'));",
    'insert into public.gear_catalog (id, kind, sport, slot, tier, cost, boost_bp, currency) values',
    STALL_ITEMS.map((i) => `  (${lit(i.id)}, 'decor', null, null, null, ${i.cost}, 0, 'coins')`).join(',\n'),
    'on conflict (id) do update set kind = excluded.kind, cost = excluded.cost, currency = excluded.currency;',
    END,
  ].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  if (process.argv.includes('--print')) {
    console.log(generatedBlock());
  } else {
    const sql = readFileSync(MIGRATION, 'utf8');
    const a = sql.indexOf(BEGIN);
    const b = sql.indexOf(END);
    if (a < 0 || b < 0) throw new Error('markers not found');
    writeFileSync(MIGRATION, sql.slice(0, a) + generatedBlock() + sql.slice(b + END.length));
    console.log(`wrote the generated block of ${MIGRATION}`);
  }
}
