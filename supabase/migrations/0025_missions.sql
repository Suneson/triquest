-- ---- weekly missions -------------------------------------------------------------------

create table if not exists public.mission_claims (
  user_id    uuid not null references auth.users (id) on delete cascade,
  week       date not null check (extract(isodow from week) = 1),
  mission_id text not null,
  coins      int not null check (coins >= 0),
  carbs      int not null check (carbs >= 0),
  claimed_at timestamptz not null default now(),
  primary key (user_id, week, mission_id)
);
alter table public.mission_claims enable row level security;
do $$ begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'mission_claims' and policyname = 'mission_claims_own') then
    create policy mission_claims_own on public.mission_claims for select using (user_id = auth.uid());
  end if;
end $$;
grant select on public.mission_claims to authenticated;

-- weeklyMissions(): the week's board, training missions first
create or replace function public.week_missions(p_week date)
returns text[] language sql immutable set search_path = public as $$
  with r as (select public.mission_rules() as j),
  k as (select ((p_week - (r.j ->> 'since')::date) / 7)::int as k, r.j from r)
  select case when k.k < 0 or extract(isodow from p_week) <> 1 then array[]::text[] else
    array(
      select k.j -> 'trainingIds' ->> ((k.k * (k.j ->> 'training')::int + i) % jsonb_array_length(k.j -> 'trainingIds'))
      from generate_series(0, (k.j ->> 'training')::int - 1) i order by i
    ) || (k.j -> 'restIds' ->> (k.k % jsonb_array_length(k.j -> 'restIds')))
  end
  from k;
$$;

-- each mission's measure (missions.js), over the week's verified sessions;
-- it only answers about the caller (0 for anyone else)
create or replace function public.mission_value(p_user uuid, p_week date, p_id text)
returns int language sql stable set search_path = public as $$
  with v as (
    select w.date, w.type,
           coalesce((w.actual ->> 'durationMin')::numeric, w.duration_min, 0) as min,
           coalesce((w.actual ->> 'distanceKm')::numeric, w.distance_km, 0) as km
    from public.workouts w
    where w.user_id = p_user and p_user = auth.uid() and w.date between p_week and p_week + 6 and public.earns(w)
  ), rest as (
    select count(*)::int as n
    from generate_series(p_week, p_week + 6, interval '1 day') d
    where p_user = auth.uid() and d::date < (now() at time zone 'utc')::date
      and not exists (select 1 from public.workouts x where x.user_id = p_user and x.date = d::date and x.completed)
  )
  select case p_id
    when 'w-sessions-3' then (select count(*) from v)::int
    when 'w-hours-4'    then floor(coalesce((select sum(greatest(min, 0)) from v), 0))::int
    when 'w-km-40'      then floor(coalesce((select sum(greatest(km, 0)) from v where type in ('run', 'bike', 'swim', 'brick')), 0))::int
    when 'w-two-sports' then (select count(distinct type) from v)::int
    when 'w-long-90'    then (select count(*) from v where min >= 90)::int
    when 'w-days-3'     then (select count(distinct date) from v)::int
    when 'w-rest-2'     then (select n from rest)
    when 'w-rest-1'     then (select n from rest)
    when 'w-recovery'   then (select count(*) from v where min >= 20 and min <= 40)::int
    else 0
  end;
$$;

create or replace function public.claim_mission(p_week date, p_mission text)
returns json language plpgsql security definer set search_path = public as $$
declare
  uid   uuid := auth.uid();
  r     jsonb := public.mission_rules();
  today date := (now() at time zone 'utc')::date;
  cur   date;
  first date;
  rows  int;
begin
  if uid is null then raise exception 'gear:not_signed_in' using errcode = '28000'; end if;
  if p_week is null or extract(isodow from p_week) <> 1 then raise exception 'gear:mission_week' using errcode = '22023'; end if;
  -- the athlete's local day can be a day either side of the server's (UTC)
  cur := (today + 1) - (extract(isodow from today + 1)::int - 1);
  first := (today - 1) - (extract(isodow from today - 1)::int - 1) - 7 * (r ->> 'claimWindow')::int;
  if p_week > cur or p_week < first or p_week < (r ->> 'since')::date then
    raise exception 'gear:mission_week' using errcode = '22023';
  end if;
  if not (p_mission = any (public.week_missions(p_week))) then raise exception 'gear:mission_unknown' using errcode = '22023'; end if;
  perform pg_advisory_xact_lock(hashtext('gear:' || uid::text));
  if exists (select 1 from public.mission_claims where user_id = uid and week = p_week and mission_id = p_mission) then
    return json_build_object('claimed', false, 'already', true);
  end if;
  if public.mission_value(uid, p_week, p_mission) < (r -> 'targets' ->> p_mission)::int then
    raise exception 'gear:mission_not_done' using errcode = '22023';
  end if;
  insert into public.mission_claims (user_id, week, mission_id, coins, carbs)
  values (uid, p_week, p_mission, (r -> 'reward' ->> 'coins')::int, (r -> 'reward' ->> 'carbs')::int)
  on conflict do nothing;
  get diagnostics rows = row_count;
  return json_build_object('claimed', rows > 0, 'already', rows = 0);
end;
$$;

-- ---- the wallet: paid missions are rank 5 -----------------------------------------------

create or replace function public.wallet_fold(p_user uuid)
returns table (coins bigint, carbs bigint, earned_coins bigint, earned_carbs bigint,
               spent_coins bigint, spent_carbs bigint, lost_coins bigint, lost_carbs bigint)
language plpgsql stable set search_path = public as $$
declare
  r     jsonb := public.gear_rules();
  cap   bigint := (r ->> 'storageCap')::bigint;
  since date := (r ->> 'since')::date;
  e     record;
  room  bigint;
begin
  earned_coins := (r ->> 'starterPurse')::bigint;  earned_carbs := (r ->> 'starterCarbs')::bigint;
  coins := least(cap, earned_coins);               carbs := least(cap, earned_carbs);
  spent_coins := 0; spent_carbs := 0; lost_coins := 0; lost_carbs := 0;
  for e in
    with days as (
      select l.date, sum(l.xp) as x from public.xp_ledger(p_user) l where l.date >= since group by l.date
    ), ev as (
      select to_char(d.date, 'YYYY-MM-DD') || 'T00:00:00.000Z' as at, 0 as rank, to_char(d.date, 'YYYY-MM-DD') as key,
             least((r ->> 'dailyCoinCap')::numeric, floor(greatest(d.x, 0) * (r ->> 'coinsPerXp')::numeric))::bigint as c,
             least((r ->> 'dailyCarbCap')::numeric, floor(greatest(d.x, 0) * (r ->> 'carbsPerXp')::numeric))::bigint as g
      from days d
      union all
      select to_char(q.day, 'YYYY-MM-DD') || 'T00:00:00.000Z', 1, q.quest_id,
             (public.quest_reward(q.quest_id) ->> 'coins')::bigint, (public.quest_reward(q.quest_id) ->> 'carbs')::bigint
      from public.quest_completions q
      where q.user_id = p_user and q.day >= since and public.quest_reward(q.quest_id) is not null
      union all
      select to_char(s.created_at at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'), 2, lpad(s.id::text, 12, '0'),
             case when s.currency = 'coins' then -s.coins else 0 end,
             case when s.currency = 'carbs' then -s.coins else 0 end
      from public.coin_spends s where s.user_id = p_user
      union all
      select to_char(m.created_at at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'), 3, lpad(m.id::text, 12, '0'),
             m.coins::bigint, 0
      from public.coin_moves m where m.user_id = p_user
      union all
      select to_char(a.at at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'), 4, a.sport || ':' || a.tier,
             a.coins::bigint, 0
      from public.collection_awards(p_user) a
      union all
      select to_char(m.claimed_at at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'), 5,
             to_char(m.week, 'YYYY-MM-DD') || ':' || m.mission_id, m.coins::bigint, m.carbs::bigint
      from public.mission_claims m where m.user_id = p_user
    )
    select * from ev order by at collate "C", rank, key collate "C"
  loop
    if e.c > 0 then
      room := greatest(0, cap - coins);
      coins := coins + least(e.c, room); earned_coins := earned_coins + e.c; lost_coins := lost_coins + greatest(0, e.c - room);
    elsif e.c < 0 then
      coins := coins + e.c; spent_coins := spent_coins - e.c;
    end if;
    if e.g > 0 then
      room := greatest(0, cap - carbs);
      carbs := carbs + least(e.g, room); earned_carbs := earned_carbs + e.g; lost_carbs := lost_carbs + greatest(0, e.g - room);
    elsif e.g < 0 then
      carbs := carbs + e.g; spent_carbs := spent_carbs - e.g;
    end if;
  end loop;
  return next;
end;
$$;


-- ---- the daily stall ---------------------------------------------------------------------

-- stallFor(): the item on a UTC day, or null before the stall opened
create or replace function public.stall_item(p_day date)
returns text language sql immutable set search_path = public as $$
  select case when p_day < (s ->> 'since')::date then null
    else s -> 'items' ->> ((p_day - (s ->> 'since')::date) % jsonb_array_length(s -> 'items')) end
  from (select public.stall_rules() as s) x;
$$;

create or replace function public.buy_stall(p_item text)
returns json language plpgsql security definer set search_path = public as $$
declare
  uid uuid := auth.uid();
  c   public.gear_catalog;
  bal bigint;
begin
  if uid is null then raise exception 'gear:not_signed_in' using errcode = '28000'; end if;
  perform pg_advisory_xact_lock(hashtext('gear:' || uid::text));
  select * into c from public.gear_catalog where id = p_item and kind = 'prop' and slot = 'decor';
  if not found then raise exception 'gear:unknown_item' using errcode = '22023'; end if;
  if public.stall_item((now() at time zone 'utc')::date) is distinct from p_item then
    raise exception 'gear:stall_gone' using errcode = '22023';
  end if;
  if exists (select 1 from public.user_gear where user_id = uid and item_id = c.id) then
    raise exception 'gear:owned' using errcode = '22023';
  end if;
  select f.coins into bal from public.wallet_fold(uid) f;
  if bal < c.cost then raise exception 'gear:insufficient' using errcode = '22023'; end if;
  insert into public.coin_spends (user_id, item_id, coins, currency) values (uid, c.id, c.cost, 'coins');
  insert into public.user_gear (user_id, item_id) values (uid, c.id);
  return public.wallet_for(uid);
end;
$$;

-- buy_gear() as in 0022, but the stall's items aren't for sale here
create or replace function public.buy_gear(p_item_id text)
returns json language plpgsql security definer set search_path = public as $$
declare
  uid  uuid := auth.uid();
  c    public.gear_catalog;
  bal  bigint;
  sid  bigint;
  mins int;
  pick record;
begin
  if uid is null then raise exception 'gear:not_signed_in' using errcode = '28000'; end if;
  perform pg_advisory_xact_lock(hashtext('gear:' || uid::text));
  perform public.workshop_settle(uid);
  select * into c from public.gear_catalog where id = p_item_id;
  if not found then raise exception 'gear:unknown_item' using errcode = '22023'; end if;
  -- the stall's items are only sold by buy_stall(), on their day
  if c.kind = 'prop' and c.slot = 'decor' then raise exception 'gear:stall_only' using errcode = '22023'; end if;
  if c.kind in ('gear', 'prop', 'kit') then
    if c.kind = 'gear' and c.tier = 0 then raise exception 'gear:starter' using errcode = '22023'; end if;
    if exists (select 1 from public.user_gear where user_id = uid and item_id = c.id) then
      raise exception 'gear:owned' using errcode = '22023';
    end if;
    if exists (select 1 from public.workshop_jobs where user_id = uid and item_id = c.id and state = 'queued') then
      raise exception 'gear:in_workshop' using errcode = '22023';
    end if;
    -- the tier below must be owned or already in the workshop ahead of it
    if c.kind = 'gear' and c.tier > 1 and not exists (
      select 1 from public.gear_catalog p
      where p.kind = 'gear' and p.sport = c.sport and p.slot = c.slot and p.tier = c.tier - 1
        and (exists (select 1 from public.user_gear g where g.user_id = uid and g.item_id = p.id)
          or exists (select 1 from public.workshop_jobs j where j.user_id = uid and j.item_id = p.id and j.state = 'queued'))
    ) then
      raise exception 'gear:tier_locked' using errcode = '22023';
    end if;
  else -- fuel
    if public.fuel_held(uid, c.id) >= (public.gear_rules() -> 'fuel' -> 'items' -> c.id ->> 'maxHeld')::int then
      raise exception 'gear:fuel_full' using errcode = '22023';
    end if;
  end if;
  select case when c.currency = 'carbs' then f.carbs else f.coins end into bal from public.wallet_fold(uid) f;
  if bal < c.cost then raise exception 'gear:insufficient' using errcode = '22023'; end if;
  insert into public.coin_spends (user_id, item_id, coins, currency) values (uid, c.id, c.cost, c.currency) returning id into sid;
  if c.kind = 'kit' then
    insert into public.user_gear (user_id, item_id) values (uid, c.id);
  elsif c.kind in ('gear', 'prop') then
    mins := public.workshop_fit_min(c.id);
    -- placeJob(): the bay that frees up first (lowest number on a tie), from then or now
    select b.bay, greatest(now(), coalesce(max(j.finishes_at), now())) as start_at into pick
    from generate_series(1, public.workshop_bays(uid)) b(bay)
    left join public.workshop_jobs j on j.user_id = uid and j.bay = b.bay and j.state = 'queued' and j.finishes_at > now()
    group by b.bay
    order by 2, 1
    limit 1;
    insert into public.workshop_jobs (user_id, item_id, spend_id, cost, bay, started_at, finishes_at)
    values (uid, c.id, sid, c.cost, pick.bay, pick.start_at, pick.start_at + make_interval(mins => mins));
  end if;
  return public.wallet_for(uid);
end;
$$;


