-- 0023: collections, blueprints and prestige (docs/LOOP.md §4). Mirrors
-- js/core/collections.js; tests/collections-sql.test.js runs both over the same cases.
--
--   - Collections: a sport's four slots at tier N or better complete its tier-N
--     set, at the moment the last piece became yours (a finished workshop job
--     counts from its finish). Each set pays setCoins once, as an earning in
--     wallet_fold() (rank 4), so it's derived, never stored, and can't be paid twice.
--   - Blueprints: one fragment per mission completed since fragmentsSince.
--     build_blueprint() spends a rare prop's fragments and builds it at once.
--     Rare props are never in gear_catalog, so buy_gear() can't sell them.
--   - Prestige: at prestige.level in a discipline (boosted XP since the last
--     reset, as the Profile shows it), prestige() records a star and the XP it
--     was taken at. Each star adds bonusBp to that discipline's boost from then
--     on, outside the gear cap. Ranks read base XP and never see it.

